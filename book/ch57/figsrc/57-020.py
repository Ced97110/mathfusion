import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
u = 10; ox, oy = 26, 20
P = lambda x, y: (ox + x * u, oy + y * u)
for i in range(-2, 5): line(ax, [P(i, -1), P(i, 3)], 'fixe', lw=0.2)
for j in range(-1, 4): line(ax, [P(-2, j), P(4, j)], 'fixe', lw=0.2)
arrow(ax, P(-2, 0), P(4.5, 0), 'fixe', lw=0.7); arrow(ax, P(0, -1), P(0, 3.5), 'fixe', lw=0.7)
line(ax, [P(2, 1), P(1, 3)], 'autre', lw=0.9, dash=True); line(ax, [P(-1, 2), P(1, 3)], 'sujet', lw=0.9, dash=True)
arrow(ax, P(0, 0), P(4, 2), 'varie', lw=1.3)
arrow(ax, P(0, 0), P(-2, -1), 'varie', lw=1.3)
arrow(ax, P(0, 0), P(2, 1), 'sujet', lw=1.7)
arrow(ax, P(0, 0), P(-1, 2), 'autre', lw=1.7)
arrow(ax, P(0, 0), P(1, 3), 'resultat', lw=1.7)
text(ax, *P(1.5, 0.25), 'v', 'sujet', 'm', weight='bold')
text(ax, *P(4.1, 2.35), '2v', 'varie', 'm', ha='left', weight='bold')
text(ax, *P(-2.0, -1.45), '−v', 'varie', 'm', weight='bold')
text(ax, *P(-1.2, 2.3), 'w', 'autre', 'm', ha='right', weight='bold')
text(ax, *P(1.2, 3.3), 'v + w', 'resultat', 'm', ha='left', weight='bold')
save(fig, '57-020')
