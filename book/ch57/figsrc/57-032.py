import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
ox, oy, u = 16, 8, 9.0
P = lambda x, y: (ox + x * u, oy + y * u)
arrow(ax, P(-1.2, 0), P(3, 0), 'fixe', lw=0.5)
arrow(ax, P(0, -0.5), P(0, 5.2), 'fixe', lw=0.5)
arrow(ax, P(0, 0), P(2, 1), 'sujet', lw=1.2)
arrow(ax, P(0, 0), P(-1, 2), 'autre', lw=1.2)
arrow(ax, P(0, 0), P(1, 3), 'resultat', lw=1.2)
line(ax, [P(2, 1), P(1, 3)], 'fixe', dash=True, lw=0.6)
line(ax, [P(-1, 2), P(1, 3)], 'fixe', dash=True, lw=0.6)
text(ax, P(2, 1)[0] + 3, P(2, 1)[1] - 2.5, r'$v$', 'sujet', 'm')
text(ax, P(-1, 2)[0] - 3, P(-1, 2)[1], r'$w$', 'autre', 'm')
text(ax, P(1, 3)[0] - 1, P(1, 3)[1] + 3, r'$v+w$', 'resultat', 'm')
box(ax, 50, 42, 36, 12, 'sujet', label="d'abord : la figure", size='s')
box(ax, 50, 24, 36, 12, 'autre', label='ensuite : quatre règles', size='s')
box(ax, 50, 6, 36, 12, 'resultat', label='vérifiables sur les flèches', size='s')
arrow(ax, (68, 41.5), (68, 36.5), 'varie')
arrow(ax, (68, 23.5), (68, 18.5), 'varie')
save(fig, '57-032')
