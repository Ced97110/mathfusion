import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(64)
O = (14, 8); u = 6
P = lambda a, b: (O[0] + u * a, O[1] + u * b)
line(ax, [P(-2, 0), P(8, 0)], 'fixe', lw=0.5)
line(ax, [P(0, -0.4), P(0, 7)], 'fixe', lw=0.5)
line(ax, [P(0, 0), P(6, 2.4)], 'sujet', dash=True)
arrow(ax, P(0, 0), P(2, 0.8), 'sujet', lw=1.6)
arrow(ax, P(0, 0), P(-0.8, 2), 'varie', lw=1.6)
arrow(ax, P(6, 2.4), P(4.4, 6.4), 'varie', lw=1.2)
arrow(ax, P(0, 0), P(4.4, 6.4), 'resultat', lw=1.6)
text(ax, 27, 11.5, '$v$', 'sujet', 's')
text(ax, 7.5, 22, '$Tv$', 'varie', 's')
text(ax, 54, 21, '3$v$', 'sujet', 's')
text(ax, 50, 37, '2$Tv$', 'varie', 's', ha='left')
text(ax, 46, 52, '(4,4 ; 6,4)', 'resultat', 's')
text(ax, 2, 61, '$x$ agit par $Tv$', 'fixe', 's', ha='left')
text(ax, 2, 55, '2$x$ + 3 agit par :', 'resultat', 's', ha='left')
text(ax, 2, 50, '2$Tv$ + 3$v$', 'resultat', 's', ha='left')
