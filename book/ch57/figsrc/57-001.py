import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(58)
u = 10; ox, oy = 44, 10
P = lambda x, y: (ox + x * u, oy + y * u)
for i in range(-3, 4): line(ax, [P(i, -1), P(i, 4)], 'fixe', lw=0.2)
for j in range(-1, 5): line(ax, [P(-3, j), P(3, j)], 'fixe', lw=0.2)
arrow(ax, P(-3, 0), P(3.4, 0), 'fixe', lw=0.7); arrow(ax, P(0, -1), P(0, 4.4), 'fixe', lw=0.7)
# point A (2, 1)
line(ax, [P(0, 0), P(2, 0)], 'varie', lw=1.6); line(ax, [P(2, 0), P(2, 1)], 'varie', lw=1.6)
disc(ax, *P(2, 1), 1.1, 'sujet')
text(ax, *P(1, -0.6), '2 à droite', 'varie', 's')
text(ax, *P(2.15, 0.5), '1 en haut', 'varie', 's', ha='left')
text(ax, *P(2, 1.55), '(2, 1)', 'sujet', 'm')
# point B (-1, 2)
line(ax, [P(0, 0), P(-1, 0)], 'varie', lw=1.6); line(ax, [P(-1, 0), P(-1, 2)], 'varie', lw=1.6)
disc(ax, *P(-1, 2), 1.1, 'sujet')
text(ax, *P(-1, -0.6), '1 à gauche', 'varie', 's')
text(ax, *P(-1.15, 1), '2 en haut', 'varie', 's', ha='right')
text(ax, *P(-1, 2.55), '(−1, 2)', 'sujet', 'm')
save(fig, '57-001')
