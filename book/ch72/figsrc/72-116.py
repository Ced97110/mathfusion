import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *

fig, ax = canvas(80)
O = (30, 38); L = 26; a = math.radians(35)
u1 = (O[0] + L * math.cos(a), O[1] + L * math.sin(a))
u2 = (O[0] + L * math.cos(a), O[1] - L * math.sin(a))
mu2 = (O[0] - L * math.cos(a), O[1] + L * math.sin(a))
s = (O[0] + 2 * L * math.cos(a), O[1])
text(ax, 44, 77, r'schéma du plan de $u_1$ et $u_2$', 'fixe', 's')
line(ax, [(O[0], 22), (O[0], 62)], 'fixe', lw=0.8, dash=True)
text(ax, O[0], 66, 'droite du pli', 'fixe', 's')
arrow(ax, O, u1, 'sujet', lw=1.6)
arrow(ax, O, u2, 'autre', lw=1.6)
arrow(ax, O, s, 'resultat', lw=2.0)
line(ax, [u2, u1], 'limite', lw=1.4, dash=True)
arrow(ax, O, mu2, 'autre', lw=1.0)
arrow(ax, (u1[0] - 1, u1[1] + 3), (mu2[0] + 1, mu2[1] + 3), 'varie', lw=1.2, curve=0.35)
text(ax, 44, 60, r'$S_s$', 'varie', 'm')
text(ax, u1[0] + 1, u1[1] + 4.5, r'$u_1$ : carré 1', 'sujet', 's', ha='left')
text(ax, u2[0] + 1, u2[1] - 4, r'$u_2$ : carré 1', 'autre', 's', ha='left')
text(ax, mu2[0], mu2[1] - 4.5, r'$-u_2$', 'autre', 's')
text(ax, s[0] + 1, s[1] + 3.5, r'$s$ : carré 4', 'resultat', 's', ha='right')
text(ax, u1[0] + 2.5, O[1] + 9, r'$d$ : carré 0', 'limite', 's', ha='left')
text(ax, 44, 12, r'$S_s(u_1)=-u_2$', 'resultat', 'l', weight='bold')
text(ax, 44, 5, 'd de carré 0 : on prend s', 'encre', 's')
save(fig, '72-116')
