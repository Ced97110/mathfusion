import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
ox, oy, u = 44, 40, 17
Q = lambda x, y: (ox + x * u, oy + y * u)
poly(ax, [Q(1, 1), Q(-1, 1), Q(-1, -1), Q(1, -1)], 'sujet')
line(ax, [Q(-1.3, 0), Q(1.3, 0)], 'fixe', lw=1.2)
line(ax, [Q(-1.25, -1.25), Q(1.12, 1.12)], 'fixe', lw=1.2, dash=True)
text(ax, Q(-1.3, 0)[0] + 1, Q(-1.3, 0)[1] + 3, 'axe horizontal', 'fixe', 's', ha='left')
text(ax, Q(-1.25, -1.25)[0] + 8, Q(-1.25, -1.25)[1] - 2, 'diagonale', 'fixe', 's')
arrow(ax, Q(1, 0.85), Q(1, -0.85), 'varie')
arrow(ax, Q(0.85, -0.85), Q(-0.85, 0.85), 'varie')
arrow(ax, Q(0.85, 1.05), Q(-0.85, 1.05), 'resultat', lw=1.4, curve=0.414)
disc(ax, *Q(1, 1), 1.3, 'sujet'); disc(ax, *Q(1, -1), 1.3, 'varie'); disc(ax, *Q(-1, 1), 1.3, 'resultat')
text(ax, Q(1, 1)[0] + 3.5, Q(1, 1)[1] + 3, '(1, 1)', 'sujet', 's', ha='left')
text(ax, Q(1, -1)[0] + 2.5, Q(1, -1)[1] - 2, '(1, −1)', 'varie', 's', ha='left')
text(ax, Q(-1, 1)[0] - 2.5, Q(-1, 1)[1] + 2, '(−1, 1)', 'resultat', 's', ha='right')
text(ax, Q(1, 0)[0] + 3, Q(1, 0)[1] - 5, 'pli 1', 'varie', 's', ha='left')
text(ax, Q(-0.2, 0.7)[0], Q(-0.2, 0.7)[1], 'pli 2', 'varie', 's')
text(ax, 44, 72, r'quart de tour $r$', 'resultat', 'm')
save(fig, '72-136')
