import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig,ax=canvas(70)
text(ax,44,64,'1. calcul : 9 − 4 = 5','encre','m')
f=numberline(ax,8,80,50,0,10,1,labels=False)
for v in (0,5,9): text(ax,f(v),46,str(v),'fixe','s')
disc(ax,f(9),50,1.4,'sujet'); arrow(ax,(f(9),54),(f(5),54),'varie'); text(ax,(f(9)+f(5))/2,57.5,'recule de 4','varie','s')
disc(ax,f(5),50,1.4,'varie',fill=False)
text(ax,44,37,'2. contrôle : 4 + 5 = 9','encre','m')
numberline(ax,8,80,22,0,10,1,labels=False)
for v in (0,4,9): text(ax,f(v),18,str(v),'fixe','s')
disc(ax,f(4),22,1.2,'fixe'); arrow(ax,(f(4),26),(f(9),26),'autre'); text(ax,(f(4)+f(9))/2,29.5,'avance de 5','autre','s')
disc(ax,f(9),22,1.6,'resultat'); line(ax,[(f(9),24),(f(9),44.5)],'resultat',dash=True)
text(ax,44,4,'on retombe sur 9 : 5 accepté','resultat','s')
brace(ax,f(4),f(9),15,'sujet',label='4 + ? = 9 donne ? = 5',down=True)
save(fig,'02-047')
