import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig,ax=canvas(78)
f=lambda v: 6+5.2*(v+5)
text(ax,3,72,'ch. 2 : soustraction','encre','s',ha='left')
numberline(ax,32,84,58,0,10,step=1,labels=False,role='fixe',arrow_right=False)
text(ax,f(0),53,'0','fixe','s')
disc(ax,f(9),58,1.2,'sujet'); text(ax,f(9),53,'9','sujet','s')
disc(ax,f(5),58,1.2,'resultat'); text(ax,f(5),53,'5','resultat','s')
arrow(ax,(f(9),62),(f(5),62),'varie'); text(ax,(f(9)+f(5))/2,66,'moins 4 : reculer de 4','varie','s')
text(ax,3,44,'ch. 13 : addition','encre','s',ha='left')
numberline(ax,32,84,22,0,10,step=1,labels=False,role='fixe',arrow_right=False)
line(ax,[(f(-5),22),(f(0),22)],'fixe',dash=True)
for v in (-5,-4,-3,-2,-1): line(ax,[(f(v),20.8),(f(v),23.2)],'fixe',dash=True)
text(ax,f(0),17,'0','fixe','s')
disc(ax,f(9),22,1.2,'sujet'); disc(ax,f(5),22,1.2,'resultat')
disc(ax,f(-4),22,1.3,'autre',fill=False); text(ax,f(-4),17,'opposé de 4','autre','s')
arrow(ax,(f(4),34),(f(0),34),'autre'); line(ax,[(f(4),22),(f(4),34)],'autre',dash=True)
text(ax,(f(4)+f(0))/2,38,'ajouté à 4 : ramène à 0','autre','s')
arrow(ax,(f(9),26),(f(5),26),'varie'); text(ax,(f(9)+f(5))/2,30,"plus l'opposé de 4",'varie','s')
save(fig,'02-080')
