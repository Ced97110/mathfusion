import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
u = 13; wx, gy = 14, 10
foot = (wx + 1.5 * u, gy); top = (wx, gy + math.sqrt(25 - 2.25) * u)
line(ax, [(wx, gy), (wx, top[1] + 3)], 'fixe', lw=1.6)
line(ax, [(wx, gy), foot], 'varie', lw=2.2)
line(ax, [foot, top], 'sujet', lw=2.2)
line(ax, [(wx + 3, gy), (wx + 3, gy + 3), (wx, gy + 3)], 'fixe', lw=0.7)
th0 = 180 - math.degrees(math.acos(0.3))
line(ax, [(foot[0] + 7 * math.cos(math.radians(a)), gy + 7 * math.sin(math.radians(a))) for a in [th0 + (180 - th0) * i / 30 for i in range(31)]], 'resultat', lw=1.2)
text(ax, foot[0] - 11, gy + 6, r'$\theta$', 'resultat', 'm')
text(ax, wx, top[1] + 6, 'mur', 'fixe', 's')
mid = ((foot[0] + top[0]) / 2, (foot[1] + top[1]) / 2)
text(ax, mid[0] + 4.5, mid[1] + 1.5, 'échelle 5 m', 'sujet', 's', rot=-(180 - th0) + 0)
text(ax, (wx + foot[0]) / 2, gy - 4, '1,5 m', 'varie', 's')
text(ax, 69, 62, r'$\cos\theta = 1{,}5\,/\,5$', 'varie', 's')
text(ax, 69, 54, r'$= 0{,}3$', 'varie', 'm')
text(ax, 69, 38, r'$\theta = \arccos\,0{,}3$', 'resultat', 's')
text(ax, 69, 30, r'$\approx 72{,}54°$', 'resultat', 'm')
arrow(ax, (69, 50), (69, 42), 'fixe')
save(fig, '33-097')
