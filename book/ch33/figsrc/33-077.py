import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(88)
cx, cy, R = 44, 52, 26
P = lambda d, r=R: (cx + r * math.cos(math.radians(d)), cy + r * math.sin(math.radians(d)))
gy0, gh = 12, 24
G = lambda xv: (cx + R * xv, gy0 + gh / math.pi * math.acos(max(-1, min(1, xv))))
line(ax, [P(d) for d in range(0, 181, 3)], 'sujet', lw=1.9)
line(ax, [(cx - R - 3, cy), (cx + R + 3, cy)], 'fixe', lw=0.6)
line(ax, [P(d, 17) for d in range(0, 160, 3)], 'varie', lw=1.5)
arrow(ax, P(156, 17), P(180, 17), 'varie', lw=1.5)
text(ax, P(0)[0] + 2.5, cy + 3.5, '0°', 'varie', 's', ha='left'); text(ax, P(180)[0] - 2.5, cy + 3.5, '180°', 'varie', 's', ha='right')
text(ax, cx, cy + 9, 'angle de 0° à 180°', 'varie', 's')
text(ax, cx, cy + R + 4, 'moitié haute', 'sujet', 'm')
arrow(ax, (cx + R, cy - 3), (cx - R, cy - 3), 'resultat', lw=1.3); text(ax, cx, cy - 7, 'abscisse : de 1 à −1', 'resultat', 's')
for xv in (-1, 1): line(ax, [(cx + R * xv, cy - 1), (cx + R * xv, gy0)], 'fixe', 0.6, True)
line(ax, [(cx - R - 3, gy0), (cx + R + 6, gy0)], 'fixe', 0.7); line(ax, [(cx, gy0 - 1), (cx, gy0 + gh + 3)], 'fixe', 0.7)
line(ax, [G(-1 + 2 * i / 60) for i in range(61)], 'varie', lw=1.6)
text(ax, cx - R, gy0 - 3.5, '−1', 'fixe', 's'); text(ax, cx + R, gy0 - 3.5, '1', 'fixe', 's')
text(ax, cx - 3, gy0 + gh, r'$\pi$', 'varie', 's'); text(ax, cx + R + 3.5, gy0 + 2.5, '0', 'varie', 's')
d = 120; px = P(d); gq = G(math.cos(math.radians(d)))
line(ax, [px, (px[0], gq[1])], 'fixe', 0.6, True); line(ax, [(cx, gq[1]), (px[0], gq[1])], 'fixe', 0.6, True)
disc(ax, *px, 1.3, 'resultat'); disc(ax, *gq, 1.3, 'resultat')
text(ax, cx + 4, gy0 + gh + 3, 'arccos descend', 'varie', 's', ha='left')
save(fig, '33-077')
