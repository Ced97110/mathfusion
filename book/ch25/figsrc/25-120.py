import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
def arc(ax, c, r, a0, a1, role="varie", n=24):
    line(ax, [(c[0] + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), c[1] + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)], role)
fig, ax = canvas(72)
A = (8, 28); B = (64, 28); L = 56; th = math.radians(36.87)
C = (A[0] + L * math.cos(th) ** 2, A[1] + L * math.cos(th) * math.sin(th))
poly(ax, [A, B, C], 'fixe')
line(ax, [A, C], 'sujet', lw=1.5); line(ax, [B, C], 'autre', lw=1.5)
d = 3.2; ux = (A[0] - C[0], A[1] - C[1]); n = math.hypot(*ux); ux = (ux[0] / n, ux[1] / n)
vx = (B[0] - C[0], B[1] - C[1]); n = math.hypot(*vx); vx = (vx[0] / n, vx[1] / n)
line(ax, [(C[0] + d * ux[0], C[1] + d * ux[1]), (C[0] + d * (ux[0] + vx[0]), C[1] + d * (ux[1] + vx[1])), (C[0] + d * vx[0], C[1] + d * vx[1])], 'fixe')
arc(ax, A, 10, 0, 36.87, 'varie'); text(ax, 21, 31.5, r'$\theta$', 'varie', 's')
arc(ax, B, 8, 180 - 53.13, 180, 'varie'); text(ax, 52, 31.8, r'90° $-$ $\theta$', 'varie', 's')
text(ax, 20, 50, r'pente $m$ = tan $\theta$', 'sujet', 's')
