box(ax, 2, 3, 24, 9, 'sujet', label=r'$m$ = tan $\theta$', size='s')
box(ax, 32, 3, 24, 9, 'varie', label=r'90° $-$ $\theta$', size='s')
box(ax, 62, 3, 24, 9, 'resultat', label=r'$-$1/$m$', size='s', weight='bold')
arrow(ax, (26.5, 7.5), (31.5, 7.5), 'encre'); arrow(ax, (56.5, 7.5), (61.5, 7.5), 'encre')
