import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
box(ax, 20, 58, 48, 10, 'sujet', label=r'$(x-1)(x^2-2)$', size='l')
f = numberline(ax, 10, 70, 30, -2, 2, 1, arrow_right=False)
r2 = math.sqrt(2)
disc(ax, f(-r2), 30, 2.2, 'varie')
disc(ax, f(r2), 30, 2.2, 'varie')
disc(ax, f(1), 30, 2.2, 'fixe')
text(ax, f(-r2), 36, r'$-\sqrt{2}$', 'varie', 's')
text(ax, f(1) - 1, 36, r'$1$', 'fixe', 's')
text(ax, f(r2) + 3, 36, r'$\sqrt{2}$', 'varie', 's')
arrow(ax, (f(-r2), 40), (f(r2), 40), 'varie', curve=-0.3, both=True)
text(ax, 40, 52, 'échange', 'varie', 's')
text(ax, 48, 19, 'racine rationnelle : ne bouge pas', 'fixe', 's')
box(ax, 14, 3, 60, 10, 'resultat', label=r'groupe de $g$ : 2 éléments', size='s')
save(fig, '65-066')
