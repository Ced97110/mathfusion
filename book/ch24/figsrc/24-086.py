import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
s = 6.0
def axes(ox, oy):
    arrow(ax, (ox, oy), (ox + 5.6 * s, oy), 'fixe', lw=0.8)
    arrow(ax, (ox, oy), (ox, oy + 5.6 * s), 'fixe', lw=0.8)
    return (lambda v: ox + s * v), (lambda v: oy + s * v)
X, Y = axes(8, 10)
line(ax, [(X(0), Y(5)), (X(5), Y(0))], 'sujet', lw=1.3)
line(ax, [(X(1.5), Y(5)), (X(4), Y(0))], 'autre', lw=1.3)
line(ax, [(X(3), Y(2)), (X(3), Y(0))], 'resultat', dash=True, lw=0.7)
line(ax, [(X(3), Y(2)), (X(0), Y(2))], 'resultat', dash=True, lw=0.7)
disc(ax, X(3), Y(2), 1.2, 'resultat')
text(ax, X(3) + 2.2, Y(0) - 2.6, r'$3$', 'resultat', 's')
text(ax, X(0) - 2.4, Y(2), r'$2$', 'resultat', 's')
X2, Y2 = axes(52, 10)
line(ax, [(X2(0), Y2(5)), (X2(5), Y2(0))], 'sujet', lw=1.3)
line(ax, [(X2(0), Y2(3.2)), (X2(3.2), Y2(0))], 'autre', lw=1.3)
text(ax, 22, 60, r'calcul : $(3, 2)$', 'resultat', 's')
text(ax, 66, 60, r'calcul : $0 = 3$', 'limite', 's')
arrow(ax, (22, 57), (22, 50), 'fixe', both=True)
arrow(ax, (66, 57), (66, 50), 'fixe', both=True)
text(ax, 22, 3.5, r'point en $(3, 2)$', 'resultat', 's')
text(ax, 66, 3.5, 'deux parallèles', 'resultat', 's')
save(fig, '24-086')
