import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(78)
# deux racines sur la droite : -2 (simple) et 1 (multiple)
f = numberline(ax, 12, 74, 58, -3, 2, arrow_right=False)
