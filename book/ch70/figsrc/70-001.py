import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(70)
s, ox, oy = 9.0, 27.0, 34.0
P = lambda x, y: (ox + s * x, oy + s * y)
arrow(ax, P(-2.7, 0), P(2.7, 0), 'fixe', lw=0.6)
arrow(ax, P(0, -2.6), P(0, 3.6), 'fixe', lw=0.6)
text(ax, P(2.7, 0)[0] + 2.5, oy - 1.5, r'$x$', 'fixe', 's')
text(ax, ox + 2.5, P(0, 3.6)[1] + 1, r'$y$', 'fixe', 's')
disc(ax, *P(0, 0), 2 * s, 'sujet', fill=False, lw=1.3)
line(ax, [P(t / 20, (t / 20) ** 2 - 2) for t in range(-46, 47)], 'varie', lw=1.3)
line(ax, [P(0, 0), P(3 ** 0.5, -1)], 'fixe', lw=0.8, dash=True)
text(ax, *P(1.65, -0.42), '2 m', 'fixe', 's')
disc(ax, *P(0, 0), 0.9, 'fixe')
text(ax, *P(-0.1, 0.6), 'arroseur', 'fixe', 's', ha='right')
for (a, b) in [(-3 ** 0.5, 1), (3 ** 0.5, 1), (0, -2)]:
    disc(ax, *P(a, b), 1.2, 'resultat')
text(ax, *P(0, -2.45), 'contacts ?', 'resultat', 's')
text(ax, 57, 60, 'bord mouillé', 'sujet', 's', ha='left')
text(ax, 57, 54, r'$x^2+y^2=4$', 'sujet', 'm', ha='left')
text(ax, 57, 40, "bord de l'allée", 'varie', 's', ha='left')
text(ax, 57, 34, r'$y=x^2-2$', 'varie', 'm', ha='left')
save(fig, '70-001')
