text(ax, f(2 ** 0.5), 59, r'$y=\sqrt{2}$ : vraie', 'resultat', 's')
text(ax, 7, 26, r'$\mathbb{Q}$', 'autre', 'l')
g = numberline(ax, 14, 68, 26, 0, 3, 1, arrow_right=True)
