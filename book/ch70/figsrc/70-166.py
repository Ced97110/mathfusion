line(ax, [(6, 22), (f(0), 22)], 'limite', lw=3)
line(ax, [(f(0), 22), (77, 22)], 'resultat', lw=3)
disc(ax, f(9), 22, 1.5, 'resultat'); disc(ax, f(-4), 22, 1.5, 'limite')
box(ax, 50, 34, 36, 9, 'resultat', label='3² = 9 : un y existe', size='s')
arrow(ax, (f(9), 34), (f(9), 24.5), 'resultat')
box(ax, 2, 34, 34, 9, 'limite', label='aucun y ne convient', size='s')
arrow(ax, (f(-4), 34), (f(-4), 24.5), 'limite')
