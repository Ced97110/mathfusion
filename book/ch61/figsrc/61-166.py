import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
O = (8, 22); s = 20; c50, s50 = math.cos(math.radians(50)), math.sin(math.radians(50))
P1 = lambda d: (O[0] + d, O[1]); P2 = lambda d: (O[0] + d * c50, O[1] + d * s50)
line(ax, [O, P1(48)], 'fixe'); line(ax, [O, P2(58)], 'fixe')
U, A, Bq, P = P1(1 * s), P1(1.5 * s), P2(1.8 * s), P2(2.7 * s)
line(ax, [U, Bq], 'sujet', lw=1.2); line(ax, [A, P], 'varie', lw=1.2)
for p, ro in ((U, 'sujet'), (A, 'varie'), (Bq, 'sujet'), (P, 'resultat')): disc(ax, p[0], p[1], 0.9, ro)
text(ax, O[0] - 2.5, O[1] - 2.5, '$O$')
text(ax, U[0], U[1] - 3.5, '1', 'sujet', 's'); text(ax, A[0], A[1] - 3.5, '1,5', 'varie', 's')
text(ax, Bq[0] - 3.8, Bq[1] + 1, '1,8', 'sujet', 's'); text(ax, P[0] - 3.8, P[1] + 1, '2,7', 'resultat', 's')
text(ax, 68, 52, '1,5 × 1,8 = 2,7', 'resultat', 's')
box(ax, 4, 2, 80, 11, 'limite', label='1,5 ÷ 0 : aucune construction', size='s')
save(fig, '61-166')
