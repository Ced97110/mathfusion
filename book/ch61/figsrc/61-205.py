import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
A = (8, 12); u = 24; th = math.radians(55)
P = lambda t: (A[0] + t * u * math.cos(th), A[1] + t * u * math.sin(th))
B, D = P(1), P(1.8); C = (A[0] + 1.5 * u, A[1]); E = (A[0] + 2.7 * u, A[1])
line(ax, [A, (A[0] + 3 * u, A[1])], 'fixe'); line(ax, [A, P(2.2)], 'fixe')
line(ax, [A, E], 'resultat', lw=2.2)
line(ax, [B, C], 'sujet', lw=1.4); line(ax, [D, E], 'varie', lw=1.4)
for p, r in [(A, 'fixe'), (B, 'sujet'), (C, 'sujet'), (D, 'varie')]: disc(ax, p[0], p[1], 1.0, r)
disc(ax, E[0], E[1], 1.6, 'resultat')
text(ax, 4.5, 8.5, 'A', 'fixe'); text(ax, B[0] - 3.2, B[1] + 1, 'B', 'sujet'); text(ax, C[0], 8, 'C', 'sujet')
text(ax, D[0] - 3.2, D[1] + 1, 'D', 'varie'); text(ax, E[0] + 4.5, E[1] + 3.5, 'E', 'resultat')
text(ax, 44, 60, '1. relier B à C', 'sujet', 's', ha='left')
text(ax, 44, 54, '2. parallèle à BC par D', 'varie', 's', ha='left')
text(ax, 44, 48, '3. elle coupe la droite en E', 'resultat', 's', ha='left')
text(ax, 70, 7.5, r'$AE=a\times b$', 'resultat', 's')
save(fig, '61-205')
