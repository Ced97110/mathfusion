import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
import math
fig, ax = canvas(72)
cx, cy, R = 24, 36, 20
disc(ax, cx, cy, R, 'fixe', fill=False, lw=0.6)
line(ax, [(cx - R - 3, cy), (cx + R + 4, cy)], 'fixe', lw=0.5)
a = math.radians(72)
z = (cx + R * math.cos(a), cy + R * math.sin(a))
zi = (cx + R * math.cos(a), cy - R * math.sin(a))
yv = (cx + 2 * R * math.cos(a), cy)
line(ax, [(cx, cy), z], 'sujet', lw=0.9)
line(ax, [(cx, cy), zi], 'sujet', lw=0.9)
line(ax, [z, yv], 'varie', lw=0.8, dash=True)
line(ax, [zi, yv], 'varie', lw=0.8, dash=True)
disc(ax, *z, 1.5, 'sujet'); disc(ax, *zi, 1.5, 'sujet'); disc(ax, *yv, 1.8, 'varie')
text(ax, z[0] + 1, z[1] + 4, r'$\zeta$', 'sujet', 'm')
text(ax, zi[0] + 1, zi[1] - 4, r'$\zeta^{-1}$', 'sujet', 'm')
text(ax, yv[0] + 4, yv[1] + 3.5, r'$y$', 'varie', 'm')
text(ax, 24, 6, r'$y=\zeta+\zeta^{-1}\approx 0{,}618$', 'varie', 's')
box(ax, 52, 52, 34, 10, 'fixe', label=r'degré 4 en $\zeta$', size='s')
arrow(ax, (69, 52), (69, 43), 'varie')
text(ax, 69, 47.5, r'$\div\,\zeta^2$', 'varie', 's', ha='left')
box(ax, 52, 32, 34, 10, 'varie', label=r'$y=\zeta+\zeta^{-1}$', size='s')
arrow(ax, (69, 32), (69, 23), 'varie')
box(ax, 52, 12, 34, 10, 'resultat', label=r'degré 2 en $y$', size='s')
save(fig, '66-090')
