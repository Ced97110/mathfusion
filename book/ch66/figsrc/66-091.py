import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(58)
cx, cy, R = 24, 29, 21
a = math.radians(72)
c, s = math.cos(a) * R, math.sin(a) * R
disc(ax, cx, cy, R, 'fixe', fill=False)
line(ax, [(cx - R - 1, cy), (cx + R + 3, cy)], 'fixe')
line(ax, [(cx + c, cy + s), (cx + c, cy - s)], 'fixe', dash=True)
line(ax, [(cx, cy), (cx + c, cy + s)], 'sujet')
line(ax, [(cx, cy), (cx + c, cy - s)], 'autre')
disc(ax, cx + c, cy + s, 1.3, 'sujet')
disc(ax, cx + c, cy - s, 1.3, 'autre')
disc(ax, cx + c, cy, 1.1, 'varie')
disc(ax, cx + 2 * c, cy, 1.4, 'resultat')
text(ax, cx + c + 4.5, cy + s + 1, 'ζ', 'sujet', 'm')
text(ax, cx + c + 6, cy - s - 1, 'ζ⁻¹', 'autre', 'm')
text(ax, cx + 2 * c + 1, cy + 3.6, 'y', 'resultat', 'm')
brace(ax, cx, cx + c, cy - 1.2, 'varie', label='c')
brace(ax, cx + c, cx + 2 * c, cy - 1.2, 'varie', label='c')
text(ax, 66, 47, 'ζ à +72°', 'sujet', 's')
text(ax, 66, 41, 'ζ⁻¹ à −72°', 'autre', 's')
text(ax, 66, 33, 'même c ≈ 0,309', 'varie', 's')
text(ax, 66, 25, 'hauteurs opposées : somme 0', 'fixe', 's')
text(ax, 66, 15, 'y = 2c ≈ 0,618', 'resultat', 'm', weight='bold')
save(fig, '66-091')
