import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(84)
cx, cy, u = 40.0, 38.0, 8.0
line(ax, [(cx - 34, cy), (cx + 34, cy)], 'fixe', lw=0.5)
line(ax, [(cx, cy - 20), (cx, cy + 30)], 'fixe', lw=0.5)
v = (3, 1); tv = (-v[1], v[0]); t2v = (-tv[1], tv[0])   # quart de tour : (x, y) -> (-y, x)
Q = lambda p: (cx + p[0] * u, cy + p[1] * u)
arrow(ax, (cx, cy), Q(v), 'sujet', lw=1.3)
arrow(ax, (cx, cy), Q(tv), 'varie', lw=1.3)
arrow(ax, (cx, cy), Q(t2v), 'autre', lw=1.3)
arrow(ax, (Q(v)[0] - 1, Q(v)[1] + 2), (Q(tv)[0] + 2, Q(tv)[1] - 3), 'varie', curve=0.3)
arrow(ax, (Q(tv)[0] - 2, Q(tv)[1] - 3), (Q(t2v)[0] - 1, Q(t2v)[1] + 3), 'varie', curve=0.3)
text(ax, Q(v)[0] + 4, Q(v)[1], r'$v$', 'sujet', 'm')
text(ax, Q(tv)[0] + 8, Q(tv)[1] + 1, r'$Tv$', 'varie', 'm')
text(ax, Q(t2v)[0] + 2, Q(t2v)[1] - 5, r'$T^2v=-v$', 'autre', 's')
text(ax, 44, 79, r'$V$ = plan, $T$ = quart de tour', 'encre', 's')
text(ax, 44, 11, r'$(x^2+1)\,v=T^2v+v=0$', 'resultat', 's', weight='bold')
text(ax, 44, 4, r'$x$ agit comme $T$', 'fixe', 's')
save(fig, '59-148')
