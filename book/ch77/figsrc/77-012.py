import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
u = 14; O = (12, 12)
P = lambda x, y: (O[0] + x * u, O[1] + y * u)
text(ax, 44, 51, r'$3+2i = 3\times1+2\times i$', 'resultat', 'l')
line(ax, [P(0, 0), P(3, 0)], 'sujet', lw=1.8); line(ax, [P(3, 0), P(3, 2)], 'autre', lw=1.8)
for k in range(1, 4): ax.plot([P(k, 0)[0]] * 2, [O[1] - 1, O[1] + 1], color=COL['sujet'], lw=0.9, zorder=3)
for k in range(1, 3): ax.plot([P(3, k)[0] - 1, P(3, k)[0] + 1], [P(3, k)[1]] * 2, color=COL['autre'], lw=0.9, zorder=3)
arrow(ax, P(0, 0), P(1, 0), 'sujet', lw=1.4); arrow(ax, P(0, 0), P(0, 1), 'autre', lw=1.4)
arrow(ax, P(0, 0), P(2.92, 1.94), 'resultat', lw=0.8)
disc(ax, P(3, 2)[0], P(3, 2)[1], 1.2, 'resultat')
text(ax, P(1, 0)[0], O[1] - 3.5, '1', 'sujet', 'm'); text(ax, O[0] - 3, P(0, 1)[1], r'$i$', 'autre', 'm')
text(ax, P(1.5, 0)[0], O[1] + 5, r'$3\times1$', 'sujet', 's')
text(ax, P(3, 1)[0] + 9, P(3, 1)[1], r'$2\times i$', 'autre', 's')
text(ax, P(3, 2)[0] + 8, P(3, 2)[1] + 3, r'$3+2i$', 'resultat', 'm')
save(fig, '77-012')
