import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(46)
u = 11; O = (62, 8)
P = lambda x, y: (O[0] + x * u, O[1] + y * u)
box(ax, 2, 22, 36, 10, 'sujet', label=r'$(2+i)\times i$')
arrow(ax, (20, 21), (20, 14), 'varie')
box(ax, 2, 4, 36, 10, 'resultat', label=r'$=-1+2i$')
arrow(ax, P(-1.4, 0), P(2.5, 0), 'fixe', lw=0.6); arrow(ax, P(0, 0), P(0, 2.5), 'fixe', lw=0.6)
arrow(ax, P(0, 0), P(2, 1), 'fixe', lw=1.2); arrow(ax, P(0, 0), P(-1, 2), 'varie', lw=1.2)
line(ax, [P(-1, 0), P(-1, 2)], 'fixe', dash=True); line(ax, [P(0, 2), P(-1, 2)], 'fixe', dash=True)
text(ax, P(2, 1)[0] - 1, P(2, 1)[1] + 4, r'$2+i$', 'fixe', 'm')
text(ax, P(-1, 2)[0] - 2, P(-1, 2)[1] + 4, r'$-1+2i$', 'varie', 'm')
text(ax, P(-1, 0)[0], O[1] - 3.5, r'$-1$', 'varie', 's'); text(ax, O[0] - 3.5, P(0, 2)[1], '2', 'varie', 's')
save(fig, '77-014')
