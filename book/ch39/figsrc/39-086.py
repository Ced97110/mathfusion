import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
c = (10, 8)
def P(r, d): return (c[0] + r * math.cos(math.radians(d)), c[1] + r * math.sin(math.radians(d)))
def arc(r, d0, d1, n=40): return [P(r, d0 + (d1 - d0) * i / n) for i in range(n + 1)]
arrow(ax, (c[0] - 3, c[1]), (c[0] + 74, c[1]), 'fixe', lw=0.6)
arrow(ax, (c[0], c[1] - 3), (c[0], c[1] + 58), 'fixe', lw=0.6)
line(ax, [c, P(54, 60)], 'fixe', lw=1.2, dash=True)
arrow(ax, c, P(40, 20), 'sujet', lw=1.5)
line(ax, arc(20, 0, 20), 'sujet', lw=1.3)
line(ax, arc(30, 0, 60), 'fixe', lw=1.0)
text(ax, P(24, 8)[0] + 3, P(24, 8)[1] + 3, 'α', 'sujet', 'l', weight='bold')
text(ax, P(34, 40)[0] + 3, P(34, 40)[1] + 1, 'θ', 'fixe', 'l', weight='bold')
text(ax, P(40, 20)[0] + 2, P(40, 20)[1] + 1, 'w = ρ cis α', 'sujet', 's', ha='left')
text(ax, P(54, 60)[0] + 2, P(54, 60)[1] + 1, 'z = r cis θ', 'fixe', 's', ha='left')
text(ax, 52, 64, 'α : angle de l’inconnue w', 'sujet', 's', ha='left')
text(ax, 52, 59, 'θ : angle du nombre z', 'fixe', 's', ha='left')
text(ax, 50, 33, 'n α = θ + k × 360°', 'varie', 's', ha='left')
