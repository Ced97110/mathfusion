import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
s = 20
O = (12, 10)
H = (O[0] + 1 * s, 10)
P = (H[0], 10 + math.sqrt(3) * s)
line(ax, [(6, 10), (46, 10)], 'fixe', lw=0.6)
line(ax, [O, P], 'fixe')
line(ax, [O, H], 'sujet', lw=2.4)
line(ax, [H, P], 'resultat', lw=2.4)
line(ax, [(H[0] - 2, 10), (H[0] - 2, 12), (H[0], 12)], 'fixe', lw=0.6)
pts = [(O[0] + 8 * math.cos(math.radians(60 * j / 20)), 10 + 8 * math.sin(math.radians(60 * j / 20))) for j in range(21)]
line(ax, pts, 'varie', lw=1.0)
disc(ax, *P, 1.4, 'fixe')
text(ax, 22, 14.5, '60°', 'varie', 's')
text(ax, 11, 14, r'$O$', 'fixe', 'm', ha='right')
text(ax, P[0], P[1] + 4.5, r'$P\,(1,\ \sqrt{3})$', 'encre', 's')
text(ax, 17.5, 33, r'$r = 2$', 'fixe', 's', rot=60)
text(ax, H[0], 5.5, r'$x = 1$', 'sujet', 's')
text(ax, H[0] + 2.5, 27, r'$y = \sqrt{3}$', 'resultat', 's', ha='left')
text(ax, 47, 48, r'$x = 2\cos 60° = 1$', 'sujet', 's', ha='left')
text(ax, 47, 40, r'$y = 2\sin 60° = \sqrt{3}$', 'resultat', 's', ha='left')
text(ax, 47, 33, r'$\approx 1{,}73$', 'resultat', 's', ha='left')
save(fig, '39-029')
