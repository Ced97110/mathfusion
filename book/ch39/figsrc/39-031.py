disc(ax, *P, 1.3, 'fixe'); disc(ax, *O, 1.0, 'fixe')
text(ax, 20, 7, r'$x = 3$', 'sujet', 's')
text(ax, H[0] + 2.5, 28, r'$y = 4$', 'sujet', 's', ha='left')
text(ax, 16, 33, r'$r = 5$', 'resultat', 's', rot=53.13)
text(ax, 54, 46, r'$3^2 = 9$', 'sujet', 's', ha='left')
