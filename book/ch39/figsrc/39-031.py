fig, ax = canvas(60)
s = 8
O = (8, 12)
H = (O[0] + 3 * s, 12)
P = (H[0], 12 + 4 * s)
line(ax, [O, P], 'resultat', lw=2.4)
line(ax, [O, H], 'sujet', lw=2.4)
line(ax, [H, P], 'sujet', lw=2.4)
