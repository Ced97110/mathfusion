import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
s = 6
O = (10, 10)
def pt(x, y): return (O[0] + x * s, O[1] + y * s)
P1, P2, H1, H2 = pt(3, 4), pt(6, 8), pt(3, 0), pt(6, 0)
line(ax, [O, P2], 'fixe', lw=0.8)
line(ax, [O, H2], 'fixe', lw=0.6)
line(ax, [H2, P2], 'autre', lw=1.6)
line(ax, [H1, P1], 'sujet', lw=2.4)
a = math.atan2(4, 3)
pts = [(O[0] + 8 * math.cos(a * j / 20), O[1] + 8 * math.sin(a * j / 20)) for j in range(21)]
line(ax, pts, 'varie', lw=1.0)
disc(ax, *P1, 1.3, 'sujet'); disc(ax, *P2, 1.3, 'autre')
text(ax, 23, 21, r'$\theta$', 'varie', 's')
text(ax, 19, 5.5, r'$x = 3$', 'sujet', 's')
text(ax, 38, 5.5, r'$x = 6$', 'autre', 's')
text(ax, 25.5, 22, r'$4$', 'sujet', 's')
text(ax, H2[0] + 2, 34, r'$y = 8$', 'autre', 's', ha='left')
text(ax, 22, 39, r'$(3,\ 4)$', 'sujet', 's')
text(ax, 40, 62, r'$(6,\ 8)$', 'autre', 's')
text(ax, 72, 62, r'$\tan\theta = y / x$', 'encre', 's')
text(ax, 72, 45, r'$4 / 3 \approx 1{,}333$', 'sujet', 's')
text(ax, 72, 36, r'$8 / 6 \approx 1{,}333$', 'autre', 's')
text(ax, 72, 26, 'même quotient', 'resultat', 's')
save(fig, '39-032')
