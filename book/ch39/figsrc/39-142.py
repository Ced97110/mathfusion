import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
ox, oy, u = 10, 10, 24
P = lambda a, b: (ox + a * u, oy + b * u)
s2 = math.sqrt(2)
arrow(ax, (ox, oy), (ox + 1.7 * u, oy), 'fixe', lw=0.6)
arrow(ax, (ox, oy), (ox, oy + 1.7 * u), 'fixe', lw=0.6)
# unit circle arc (rotation) and larger arc (enlargement)
t = [math.radians(45 * k / 20) for k in range(21)]
line(ax, [(ox + u * math.cos(v), oy + u * math.sin(v)) for v in t], 'varie', lw=1.0, dash=True)
ghost = P(1 / s2, 1 / s2)
line(ax, [(ox, oy), P(1, 0)], 'sujet', lw=1.3)
line(ax, [(ox, oy), ghost], 'varie', lw=0.9, dash=True)
arrow(ax, (ox, oy), P(1, 1), 'resultat', lw=1.3)
arrow(ax, (ghost[0] + 0.5, ghost[1] + 0.5), (P(1, 1)[0] - 1, P(1, 1)[1] - 1), 'varie', lw=0.9)
disc(ax, *P(1, 0), 1.4, 'sujet'); disc(ax, *P(1, 1), 1.4, 'resultat')
disc(ax, *ghost, 1.0, 'varie')
text(ax, P(1, 0)[0] + 2, oy - 3.5, r'$1$', 'sujet', 's', ha='left')
text(ax, P(1, 1)[0] + 3, P(1, 1)[1] + 2, r'$1+i$', 'resultat', 's', ha='left')
text(ax, ox + 16, oy + 5.5, '45°', 'varie', 's')
text(ax, 62, 56, r'multiplier par $1+i$', 'resultat', 's')
text(ax, 62, 46, '1. rotation de 45°', 'varie', 's')
text(ax, 62, 37, r'2. distances $\times\sqrt{2}$', 'varie', 's')
text(ax, 62, 25, r'$|1+i|=\sqrt{2}$', 'resultat', 's')
text(ax, 62, 14, r'$(1,0)\to(1,1)$', 'resultat', 's')
save(fig, '39-142')
