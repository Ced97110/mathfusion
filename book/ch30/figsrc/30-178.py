import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
cx, cy, R = 28, 38, 24
th = math.radians(50)
disc(ax, cx, cy, R, 'sujet', fill=False, lw=1.0)
line(ax, [(2, cy), (54, cy)], 'fixe', lw=0.6); line(ax, [(cx, 12), (cx, 64)], 'fixe', lw=0.6)
px, py = cx + R * math.cos(th), cy + R * math.sin(th)
line(ax, [(cx, cy), (px, py)], 'fixe')
line(ax, [(cx, cy), (px, cy)], 'autre', lw=1.5)
line(ax, [(px, cy), (px, py)], 'resultat', lw=1.5)
line(ax, [(cx + 7 * math.cos(a * th / 20), cy + 7 * math.sin(a * th / 20)) for a in range(21)], 'varie')
disc(ax, px, py, 1.5, 'varie')
text(ax, 37.5, 42.4, r'$\theta$', 'varie', 's')
text(ax, (cx + px) / 2, cy - 3.5, r'$\cos\theta$', 'autre', 's')
text(ax, px - 2, (cy + py) / 2 + 3, r'$\sin\theta$', 'resultat', 's', ha='right')
text(ax, 64, 65.5, r'$\cos\theta$', 'autre', 'm', ha='right')
text(ax, 67.2, 65.5, '+', 'encre', 'm')
text(ax, 70.5, 65.5, r'$i\,\sin\theta$', 'resultat', 'm', ha='left')
text(ax, 54, 56, r'$\cos\theta$ : horizontale', 'autre', 's', ha='left')
text(ax, 54, 51.5, r'$\sin\theta$ : hauteur', 'resultat', 's', ha='left')
text(ax, 54, 47, r'$i$ : repère la hauteur', 'resultat', 's', ha='left')
arrow(ax, (62, 62.5), (px + 2, py + 1.5), 'varie')
text(ax, cx, 8, 'cercle de rayon 1', 'fixe', 's')
save(fig, '30-178')
