import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
u, ox, oy = 8, 12, 8
P = lambda x, y: (ox + u*x, oy + u*y)
fig, ax = canvas(66)
for i in range(9): line(ax, [P(i, 0), P(i, 6)], 'fixe', 0.25)
for j in range(7): line(ax, [P(0, j), P(8, j)], 'fixe', 0.25)
arrow(ax, P(0, 0), P(8.4, 0), 'encre', 0.8); arrow(ax, P(0, 0), P(0, 6.4), 'encre', 0.8)
poly(ax, [P(1, 1), P(7, 1), P(6, 5)], 'sujet')
line(ax, [P(1, 1), P(7, 1)], 'encre', 1.8)
line(ax, [P(6, 5), P(6, 1)], 'encre', 1.8, dash=True)
line(ax, [P(5.65, 1), P(5.65, 1.35), P(6, 1.35)], 'encre', 0.6)
for p in ((1, 1), (7, 1), (6, 5)): disc(ax, *P(*p), 1.0, 'encre')
text(ax, P(1, 1)[0] - 5, P(1, 1)[1] + 5, 'A (1, 1)', 'encre', 'm', weight='bold')
text(ax, P(7, 1)[0] + 1, P(7, 1)[1] - 4.5, 'B (7, 1)', 'encre', 'm', weight='bold')
text(ax, P(6, 5)[0] + 10, P(6, 5)[1] + 1, 'C (6, 5)', 'encre', 'm', weight='bold')
text(ax, P(4, 1)[0], P(4, 1)[1] + 3.5, '6', 'encre', 'l', weight='bold')
text(ax, P(6, 3)[0] - 3, P(6, 3)[1], '4', 'encre', 'l', weight='bold')
text(ax, 70, 62, '½ × 6 × 4 = 12', 'resultat', 'm', weight='bold')
for x in (1, 6, 7): text(ax, P(x, 0)[0], 4.5, str(x), 'fixe', 's')
for y in (1, 5): text(ax, 9, P(0, y)[1], str(y), 'fixe', 's')
save(fig, '37-094')
