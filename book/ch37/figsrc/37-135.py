import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
k = 1.5; O = (12, 10)
f = lambda x, y: (O[0] + x * k, O[1] + y * k)
line(ax, [O, (84, 10)], 'fixe', lw=0.7)
B1, C1, Pp = f(6, 0), f(5, 4), f(30, 24)
line(ax, [O, C1], 'sujet', lw=1.2); line(ax, [C1, Pp], 'resultat', lw=1.0, dash=True)
ax.add_patch(matplotlib.patches.Arc(O, 16, 16, theta1=0, theta2=38.66, ec=COL['varie'], lw=1.0, zorder=3))
disc(ax, *B1, 1.1, 'autre'); disc(ax, *C1, 1.1, 'sujet'); disc(ax, *Pp, 1.3, 'resultat'); disc(ax, *O, 0.8, 'encre')
text(ax, B1[0] + 4, 5.5, '6 ; 0°', 'autre', 's')
text(ax, 3, 24, '6,40 ; 38,66°', 'sujet', 's', ha='left')
text(ax, Pp[0] - 3, Pp[1] + 5, '38,4 ; 38,66°', 'resultat', 's')
text(ax, 66, 26, '6 × 6,40 = 38,4', 'resultat', 's'); text(ax, 66, 20, '0° + 38,66° = 38,66°', 'varie', 's')
save(fig, '37-135')
