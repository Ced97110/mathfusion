import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
a, b, c = 40, 50, 60; s = 75
Ax = (c*c + a*a - b*b) / (2*a); A = (Ax, math.sqrt(c*c - Ax*Ax)); B = (0.0, 0.0); C = (40.0, 0.0)
ra = math.sqrt(s*(s-a)*(s-b)*(s-c))/(s-a); Ia = (s - c, -ra)
k, oy = 0.9, 37
mk = lambda ox: (lambda p: (ox + k*p[0], oy + k*p[1]))
T1, T2 = mk(8), mk(50)
cen = lambda *ps: (sum(p[0] for p in ps)/len(ps), sum(p[1] for p in ps)/len(ps))
fig, ax = canvas(93)
poly(ax, [T1(A), T1(B), T1(C)], 'sujet'); poly(ax, [T1(B), T1(Ia), T1(C)], 'varie')
poly(ax, [T2(A), T2(B), T2(Ia)], 'sujet'); poly(ax, [T2(A), T2(Ia), T2(C)], 'autre')
text(ax, *T1(cen(A, B, C)), '992,2', 'sujet', 'm')
text(ax, *T1(cen(B, Ia, C)), '566,9', 'varie', 'm')
text(ax, *T2(cen(A, B, Ia)), '850,4', 'sujet', 'm')
text(ax, *T2(cen(A, Ia, C)), '708,7', 'autre', 'm')
sh = lambda T, p, dx, dy: (T(p)[0] + dx, T(p)[1] + dy)
text(ax, *sh(T1, A, 0, 3.2), 'A', 'encre', 'l', weight='bold')
text(ax, *sh(T1, B, -3, 0), 'B', 'encre', 'l', weight='bold')
text(ax, *sh(T1, C, 3, 0), 'C', 'encre', 'l', weight='bold')
text(ax, *sh(T1, Ia, 5, -1), r'$I_a$', 'encre', 'l', weight='bold')
text(ax, 26, 89, '992,2 + 566,9 = 1 559,1', 'encre', 'm')
text(ax, 68, 89, '850,4 + 708,7 = 1 559,1', 'encre', 'm')
text(ax, 26, 3.5, 'coupe selon BC', 'fixe', 'm')
text(ax, 68, 3.5, r'coupe selon A$I_a$', 'fixe', 'm')
save(fig, '37-074')
