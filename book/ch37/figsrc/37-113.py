import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
import math
from matplotlib.patches import Arc
# left : 40, 50, 60 (O dedans)
s1 = 0.6; R1 = 80 / math.sqrt(7)
A, B, C = (0, 0), (60, 0), (37.5, math.sqrt(1093.75)); O = (30, math.sqrt(R1 * R1 - 900))
c1 = (23, 33)
T1 = lambda p: (c1[0] + (p[0] - O[0]) * s1, c1[1] + (p[1] - O[1]) * s1)
disc(ax, *c1, R1 * s1, 'fixe', fill=False, lw=0.8)
poly(ax, [T1(A), T1(B), T1(C)], 'sujet')
disc(ax, *c1, 1.1, 'resultat'); text(ax, c1[0], c1[1] - 3.2, 'O', 'resultat', 's', weight='bold')
text(ax, T1(A)[0] + 7, T1(A)[1] + 2.3, '41,41°', 'sujet', 's'); text(ax, T1(B)[0] - 7, T1(B)[1] + 2.3, '55,77°', 'sujet', 's')
text(ax, T1(C)[0], T1(C)[1] - 3.2, '82,82°', 'sujet', 's')
text(ax, 23, 60, 'trois angles aigus', 'resultat', 's'); text(ax, 23, 4, 'O dans le triangle', 'resultat', 's')
# droite : 3, 5, 7, angle 120° (O dehors)
s2 = 4.3; R2 = 7 / math.sqrt(3)
P0, P1, P2 = (0, 0), (5, 0), (-1.5, 3 * math.sin(math.radians(120)))
O2 = (2.5, 3.175)
c2 = (65, 33)
T2 = lambda p: (c2[0] + (p[0] - O2[0]) * s2, c2[1] + (p[1] - O2[1]) * s2)
disc(ax, *c2, R2 * s2, 'fixe', fill=False, lw=0.8)
poly(ax, [T2(P0), T2(P1), T2(P2)], 'sujet')
disc(ax, *c2, 1.1, 'varie'); text(ax, c2[0] + 3, c2[1] + 1.5, 'O', 'varie', 's', weight='bold')
text(ax, T2(P0)[0] + 3, T2(P0)[1] + 4.5, '120°', 'sujet', 's')
text(ax, 65, 60, 'un angle obtus', 'varie', 's'); text(ax, 65, 4, 'O hors du triangle', 'varie', 's')
save(fig, '37-113')
