import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
u, ox, oy = 9, 8, 10
P = lambda x, y: (ox + u*x, oy + u*y)
fig, ax = canvas(46)
for i in range(9): line(ax, [P(i, 0), P(i, 3)], 'fixe', 0.25)
for j in range(4): line(ax, [P(0, j), P(8, j)], 'fixe', 0.25)
arrow(ax, P(0, 0), P(8.4, 0), 'encre', 0.8); arrow(ax, P(0, 0), P(0, 3.4), 'encre', 0.8)
line(ax, [P(1, 1), P(7, 1)], 'fixe', 0.8, dash=True)
arrow(ax, P(0, 0), P(7, 0), 'varie', 1.8); arrow(ax, P(7, 0), P(7, 1), 'varie', 1.8)
disc(ax, *P(1, 1), 1.6, 'fixe'); disc(ax, *P(7, 1), 1.9, 'sujet')
text(ax, P(1, 1)[0], P(1, 1)[1] + 3.5, 'A', 'fixe', 'm', weight='bold')
text(ax, P(7, 1)[0], P(7, 1)[1] + 3.5, 'B', 'sujet', 'm', weight='bold')
text(ax, P(4, 1)[0], P(4, 1)[1] + 4.5, 'y₁ = y₂ = 1', 'fixe', 'm')
text(ax, P(3.5, 0)[0], P(3.5, 0)[1] + 3.5, 'x₂ = 7', 'varie', 'm')
text(ax, P(7, 0.5)[0] + 2.5, P(7, 0.5)[1] - 1, 'y₂ = 1', 'varie', 'm', ha='left')
text(ax, 56, 41, 'B (x₂, y₂) = (7, 1)', 'sujet', 'm', weight='bold')
for x in (1, 7): text(ax, P(x, 0)[0], 6, str(x), 'fixe', 's')
text(ax, 5, P(0, 1)[1], '1', 'fixe', 's')
save(fig, '37-096')
