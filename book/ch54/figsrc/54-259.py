import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(92)
pb = lambda v: (v ** 4 + v + 1) % 2
assert (pb(0), pb(1)) == (1, 1)
box(ax, 4, 78, 80, 11, 'sujet', label=r'$\bar p = x^4+x+1$ sur $\mathbb{Z}/2$')
arrow(ax, (24, 77), (24, 69), 'varie'); arrow(ax, (64, 77), (64, 69), 'varie')
text(ax, 24, 64, 'cas 1 + 3', 'varie', 's')
text(ax, 64, 64, 'cas 2 + 2', 'varie', 's')
box(ax, 3, 36, 40, 22, 'fixe')
text(ax, 23, 53, r'$\bar p(0)=1$', 'fixe', 's')
text(ax, 23, 46, r'$\bar p(1)=1$', 'fixe', 's')
text(ax, 23, 39, 'aucune racine', 'resultat', 's')
box(ax, 45, 36, 40, 22, 'fixe')
text(ax, 65, 53, r'seul produit sans racine', 'fixe', 's')
text(ax, 65, 46, r'$(x^2+x+1)^2$', 'autre', 's')
text(ax, 65, 39, r'$=x^4+x^2+1\neq\bar p$', 'limite', 's')
arrow(ax, (44, 34), (44, 24), 'resultat')
box(ax, 10, 8, 68, 15, 'resultat', label=r'$\bar p$ irréductible')
save(fig, '54-259')
