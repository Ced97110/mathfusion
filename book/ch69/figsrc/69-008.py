arrow(ax, (f(-2), y + 2.2), (f(4), y + 2.2), 'sujet', curve=-0.5)
arrow(ax, (f(1.5), y + 2.4), (f(2.25), y + 2.4), 'varie', curve=-0.8)
text(ax, f(0), 25, '0', 'fixe', 's')
text(ax, f(-2), 25, 'a = −2', 'sujet', 's')
text(ax, f(-1), 19.5, r'$i^2$ devrait être en $-1$', 'limite', 's')
text(ax, f(1.5), 25, 'b = 1,5', 'varie', 's')
