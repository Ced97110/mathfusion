import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(58)
y = 30
f = numberline(ax, 8, 78, y, -3, 5, labels=False, arrow_right=False)
box(ax, f(-3), 8, f(0) - f(-3) - 0.6, 7, 'autre', label='N : à gauche de 0', size='s')
box(ax, f(0) + 0.6, 8, f(5) - f(0) - 0.6, 7, 'resultat', label='P : à droite de 0', size='s')
def sq(x, role):
    poly(ax, [(x - 1.5, y - 1.5), (x + 1.5, y - 1.5), (x + 1.5, y + 1.5), (x - 1.5, y + 1.5)], role)
disc(ax, f(-2), y, 2, 'sujet')
disc(ax, f(1.5), y, 2, 'varie')
sq(f(4), 'sujet')
sq(f(2.25), 'varie')
line(ax, [(f(-1) - 1.6, y - 1.6), (f(-1) + 1.6, y + 1.6)], 'limite', lw=1.5)
