import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
cx, cy, R = 30, 40, 24
ax.add_patch(Circle((cx, cy), R, ec=COL['fixe'], fc='none', lw=0.7, zorder=1))
arrow(ax, (cx - R - 3, cy), (cx + R + 4, cy), 'fixe', lw=0.7)
line(ax, [(cx, cy - R - 3), (cx, cy + R + 3)], 'fixe', lw=0.7)
a = math.radians(72)
wx, wy = cx + R * math.cos(a), cy + R * math.sin(a)
w4x, w4y = wx, cy - R * math.sin(a)
line(ax, [(cx, cy), (wx, wy)], 'sujet')
line(ax, [(cx, cy), (w4x, w4y)], 'sujet')
line(ax, [(wx, wy), (w4x, w4y)], 'varie', dash=True)
disc(ax, wx, wy, 1.6, 'sujet'); disc(ax, w4x, w4y, 1.6, 'sujet')
disc(ax, wx, cy, 1.2, 'resultat')
text(ax, wx + 1.5, wy + 3.2, r'$\omega$', 'sujet', 'm', ha='left')
text(ax, w4x + 1.5, w4y - 3.2, r'$\omega^4$', 'sujet', 'm', ha='left')
arrow(ax, (wx + 6, wy - 2), (wx + 6, w4y + 2), 'varie', both=True)
text(ax, wx + 8.2, cy + 5, r'$\sigma_4$', 'varie', 'm', ha='left')
text(ax, wx + 1, cy - 3.2, r'$\cos 72°$', 'resultat', 's', ha='left')
text(ax, cx + 5.5, cy + 6, r'$72°$', 'sujet', 's')
text(ax, 2, cy + 3.5, 'axe réel', 'fixe', 's', ha='left')
x0 = 74
text(ax, x0, 70, r'$H=\{1,\sigma_4\}$', 'sujet', 's')
text(ax, x0, 63, r'$\sigma_4:\ \omega\mapsto\omega^4$', 'varie', 's')
text(ax, x0, 55, 'conjugaison\ncomplexe', 'varie', 's')
arrow(ax, (x0, 48), (x0, 36), 'resultat')
box(ax, x0 - 12, 22, 24, 10, 'resultat', label=r'$K = \mathrm{Inv}\,H$', size='s')
text(ax, x0, 14, 'degré 2', 'resultat', 's')
save(fig, '63-166')
