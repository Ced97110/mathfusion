import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# r = sin 2θ : P (0,866 ; 30°). Nom 1 (0,866 ; -30°) échoue ; nom 2 (-0,866 ; 150°) réussit : symétrie par l'axe x
fig, ax = canvas(96)
o = (44, 66); u = 27
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
arrow(ax, (o[0] - 30, o[1]), (o[0] + 34, o[1]), 'fixe', lw=0.9)
text(ax, o[0] + 36, o[1] - 3, r'$x$', 'fixe', 's')
line(ax, [pt(math.sin(2 * math.radians(a)), a) for a in range(0, 361, 2)], 'sujet', lw=1.4)
r = math.sin(math.radians(60))
P, R = pt(r, 30), pt(r, -30)
line(ax, [P, R], 'fixe', lw=0.7, dash=True)
line(ax, [o, pt(1.1, 150)], 'resultat', lw=0.8, dash=True)
line(ax, [o, R], 'varie', lw=1.0, dash=True)
disc(ax, P[0], P[1], 1.4, 'sujet'); disc(ax, R[0], R[1], 1.5, 'resultat'); disc(ax, o[0], o[1], 0.9, 'encre')
text(ax, P[0] + 12, P[1] + 5, '$P$ (0,866 ; 30°)', 'sujet', 's')
text(ax, R[0] + 11, R[1] - 4, 'reflet de $P$', 'resultat', 's')
text(ax, 44, 92, r'$r = \sin 2\theta$', 'sujet', 'm')
text(ax, 22, 28, 'nom 1 : (0,866 ; −30°)', 'limite', 's')
text(ax, 22, 23, r'$\sin(-60°) = -0{,}866$', 'limite', 's')
text(ax, 22, 18, '≠ 0,866 : échec', 'limite', 's')
text(ax, 66, 28, 'nom 2 : (−0,866 ; 150°)', 'resultat', 's')
text(ax, 66, 23, r'$\sin 300° = -0{,}866$', 'resultat', 's')
text(ax, 66, 18, '= −0,866 : réussite', 'resultat', 's')
text(ax, 44, 8, 'le reflet est sur la courbe : symétrie', 'resultat', 's')
save(fig, '40-047')
