import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# (-r ; θ) est le symétrique de M par le pôle : (1 ; 1,73) -> (-1 ; -1,73), même distance 2
fig, ax = canvas(84)
o = (44, 42); u = 14
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
arrow(ax, (o[0] - 36, o[1]), (o[0] + 38, o[1]), 'fixe', lw=0.9)
arrow(ax, (o[0], o[1] - 28), (o[0], o[1] + 34), 'fixe', lw=0.9)
text(ax, o[0] + 40, o[1] - 3, r'$x$', 'fixe', 's')
text(ax, o[0] + 3, o[1] + 35, r'$y$', 'fixe', 's')
M, M3 = pt(2, 60), pt(-2, 60)
line(ax, [pt(-2.3, 60), pt(2.3, 60)], 'fixe', lw=0.7, dash=True)
line(ax, [o, M], 'sujet', lw=1.5)
line(ax, [o, M3], 'varie', lw=1.5)
arrow(ax, (M[0] + 7, M[1] - 3), (M3[0] + 7, M3[1] + 3), 'varie', lw=1.0, curve=-0.45)
disc(ax, M[0], M[1], 1.5, 'sujet'); disc(ax, M3[0], M3[1], 1.5, 'varie'); disc(ax, o[0], o[1], 0.9, 'encre')
text(ax, o[0] + 3, o[1] - 3.5, 'O', 'encre', 's')
text(ax, M[0] + 14, M[1] + 3, r'$M$ (1 ; 1,73)', 'sujet', 's')
text(ax, M3[0] - 15, M3[1] - 3, r'$M_3$ ($-$1 ; $-$1,73)', 'varie', 's')
text(ax, o[0] + 20, o[1] + 22, '× (−1)', 'varie', 's')
text(ax, o[0] - 14, o[1] + 11, r'$r$ = 2', 'sujet', 's')
text(ax, o[0] + 14, o[1] - 11, r'$|-r|$ = 2', 'varie', 's')
text(ax, 44, 9, r'$(x\,;\,y) \rightarrow (-x\,;\,-y)$ : les deux coordonnées × (−1)', 'encre', 's')
text(ax, 44, 81, 'symétrique par le pôle $O$', 'encre', 'm')
save(fig, '40-038')
