import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(64)
cx, cy, u = 44, 34, 14
S = math.sqrt(3)
P = lambda x, y: (cx + u * x, cy + u * y)
arrow(ax, (cx - 40, cy), (cx + 40, cy), 'fixe', lw=0.6)
arrow(ax, (cx, cy - 22), (cx, cy + 22), 'fixe', lw=0.6)
p, q, r = P(S, 1), P(S, -1), P(-S, -1)
line(ax, [p, r], 'resultat', lw=0.9, dash=True)
arrow(ax, (p[0], p[1] - 1.5), (q[0], q[1] + 1.5), 'varie', lw=1.2)
arrow(ax, (q[0] - 1.5, q[1]), (r[0] + 1.5, r[1]), 'varie', lw=1.2)
disc(ax, *p, 1.3, 'sujet'); disc(ax, *q, 1.3, 'varie'); disc(ax, *r, 1.3, 'resultat')
disc(ax, cx, cy, 0.8, 'fixe')
text(ax, p[0] - 2, p[1] + 3.8, r'$P$ : $r=2$, $30^\circ$', 'sujet', 's', ha='right')
text(ax, p[0] + 2.5, 34 - 7, 'reflet par\nl’axe des x', 'varie', 's', ha='left')
text(ax, 46, q[1] + 3.5, 'reflet par l’axe des y', 'varie', 's')
text(ax, q[0] + 2, q[1] - 4, r'$Q\,(1{,}732\,;\,-1)$', 'varie', 's', ha='center')
text(ax, r[0], r[1] - 4.5, r'$R\,(-1{,}732\,;\,-1)$' + '\n210°', 'resultat', 's')
text(ax, 44, 5, 'R = symétrique de P par le pôle', 'resultat', 's')
save(fig, '40-126')
