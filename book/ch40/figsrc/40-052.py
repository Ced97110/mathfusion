import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# r = 2a sin θ, a = 1 : cercle de centre (0 ; 1), rayon 1. À 90° r = 2 ; à 30° r = 1, point (0,866 ; 0,5), distance 1 au centre
fig, ax = canvas(68)
u = 22; o = (26, 8)
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
line(ax, [pt(2 * math.sin(math.radians(t)), t) for t in range(0, 181, 2)], 'sujet', lw=1.6)
arrow(ax, (o[0] - 22, o[1]), (o[0] + 24, o[1]), 'fixe', lw=0.8)
line(ax, [o, (o[0], o[1] + 2 * u + 5)], 'fixe', lw=0.7)
C = (o[0], o[1] + u); P = pt(1, 30); T = pt(2, 90)
line(ax, [o, P], 'varie', lw=1.3); line(ax, [C, P], 'resultat', lw=1.3)
disc(ax, C[0], C[1], 1.0, 'sujet', fill=False); disc(ax, P[0], P[1], 1.4, 'varie'); disc(ax, T[0], T[1], 1.4, 'sujet'); disc(ax, o[0], o[1], 0.9, 'encre')
text(ax, T[0] + 9, T[1] + 1, '90° : $r$ = 2', 'sujet', 's')
text(ax, C[0] - 8, C[1] + 1, r'$C$ (0 ; 1)', 'sujet', 's')
text(ax, P[0] + 4, P[1] - 4, '30° : $r$ = 1', 'varie', 's')
text(ax, o[0] - 4, o[1] - 3, 'O', 'encre', 's')
text(ax, 44, 64, r'$r = 2a\sin\theta$, $a = 1$', 'sujet', 'm')
text(ax, 72, 46, '1. choisir $\\theta$', 'encre', 's')
text(ax, 72, 41, '2. calculer', 'encre', 's')
text(ax, 72, 36.5, r'$2a\sin\theta$', 'encre', 's')
text(ax, 72, 31.5, '3. avancer', 'encre', 's')
text(ax, 72, 20, r'$0{,}866^2 + 0{,}5^2 = 1$', 'resultat', 's')
text(ax, 72, 15, '$CP$ = 1 = rayon', 'resultat', 's')
save(fig, '40-052')
