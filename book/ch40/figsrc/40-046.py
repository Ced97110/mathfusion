import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# Un point a plusieurs noms : le reflet de M (2 ; 60°) par l'axe x s'appelle (2 ; -60°) et (-2 ; 120°) : même point (1 ; -1,73)
fig, ax = canvas(92)
o = (44, 56); u = 14
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
arrow(ax, (o[0] - 30, o[1]), (o[0] + 36, o[1]), 'fixe', lw=0.9)
text(ax, o[0] + 38, o[1] - 3, r'$x$', 'fixe', 's')
M, R = pt(2, 60), pt(2, -60)
line(ax, [o, M], 'sujet', lw=1.3)
line(ax, [pt(-2.4, 120), pt(2.4, 120)], 'fixe', lw=0.6, dash=True)
arrow(ax, (o[0] + 0.4, o[1] - 0.6), (R[0] - 0.5, R[1] + 0.8), 'varie', lw=1.7)
b = pt(2, 120)
line(ax, [o, b], 'autre', lw=1.0, dash=True)
arrow(ax, (o[0] - 1, o[1] + 0.5), (R[0] - 3, R[1] + 3), 'autre', lw=1.2, curve=0.35)
disc(ax, M[0], M[1], 1.5, 'sujet'); disc(ax, R[0], R[1], 1.8, 'varie'); disc(ax, o[0], o[1], 0.9, 'encre')
text(ax, M[0] + 14, M[1] + 3, r'$M$ (2 ; 60°)', 'sujet', 's')
text(ax, R[0] + 20, R[1] - 2, '(1 ; −1,73)', 'varie', 's')
text(ax, R[0] + 20, R[1] - 7, 'un seul point', 'varie', 's')
text(ax, 22, 22, 'nom 1', 'varie', 's')
text(ax, 22, 17, '(2 ; −60°)', 'varie', 's')
text(ax, 22, 12, 'avancer de 2', 'varie', 's')
text(ax, 66, 22, 'nom 2', 'autre', 's')
text(ax, 66, 17, '(−2 ; 120°)', 'autre', 's')
text(ax, 66, 12, 'reculer de 2', 'autre', 's')
text(ax, b[0] - 6, b[1] + 3, '120°', 'autre', 's')
save(fig, '40-046')
