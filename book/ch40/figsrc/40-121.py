import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(82)
ox, oy, u = 20, 12, 3.4
P = lambda x, y: (ox + u * x, oy + u * y)
arrow(ax, P(-3, 0), P(8, 0), 'fixe', lw=0.6)
arrow(ax, (ox, oy - 2), P(0, 18.5), 'fixe', lw=0.6)
pt = lambda t: (-1.25 + 3 * t, 8 * t)
line(ax, [P(*pt(-0.2)), P(*pt(2.2))], 'fixe', lw=0.9)
p0, p1, p2 = P(*pt(0)), P(*pt(1)), P(*pt(2))
arrow(ax, p0, p1, 'varie', lw=1.3)
arrow(ax, p1, p2, 'varie', lw=1.3)
line(ax, [p0, (p1[0], p0[1]), p1], 'varie', lw=0.7, dash=True)
text(ax, (p0[0] + p1[0]) / 2, p0[1] - 2.8, '3', 'varie', 's')
text(ax, p1[0] + 2, (p0[1] + p1[1]) / 2, '8', 'varie', 's')
for p, s in ((p0, 't = 0'), (p1, 't = 1'), (p2, 't = 2')):
    disc(ax, p[0], p[1], 1.2, 'sujet')
text(ax, 22, 3.5, 'départ (−1,25 ; 0)', 'sujet', 's', ha='left')
text(ax, p1[0] - 2.5, p1[1] + 1.5, 't = 1\n(1,75 ; 8)', 'sujet', 's', ha='right')
text(ax, p2[0] - 2.5, p2[1] + 1.5, 't = 2\n(4,75 ; 16)', 'sujet', 's', ha='right')
text(ax, 64, 68, r'$x=-1{,}25+3t$', 'sujet', 'm')
text(ax, 64, 61, r'$y=8t$', 'sujet', 'm')
text(ax, 64, 52, 'vecteur directeur :\n3 à droite, 8 en haut', 'varie', 's')
text(ax, 64, 44, 'chaque t\ndonne un point', 'encre', 's')
save(fig, '40-121')
