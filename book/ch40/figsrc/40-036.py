import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# (r ; -θ) est le reflet de (r ; θ) par l'axe des x : r = 2, θ = 60° -> (1 ; 1,73) et (1 ; -1,73)
fig, ax = canvas(92)
o = (30, 52); u = 16
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
def arc(rad, a0, a1, role):
    n = max(2, int(abs(a1 - a0) / 3))
    line(ax, [(o[0] + rad * math.cos(math.radians(a0 + (a1 - a0) * i / n)), o[1] + rad * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)], role, lw=1.2)
arrow(ax, (o[0] - 8, o[1]), (o[0] + 42, o[1]), 'fixe', lw=0.9)
text(ax, o[0] + 44, o[1] - 3, r'$x$', 'fixe', 's')
M, M1 = pt(2, 60), pt(2, -60)
line(ax, [o, M], 'sujet', lw=1.4); line(ax, [o, M1], 'varie', lw=1.4)
line(ax, [M, M1], 'fixe', lw=0.8, dash=True)
arc(9, 0, 60, 'sujet'); arc(9, 0, -60, 'varie')
# cercle de rayon 2 en pointillé (même distance)
line(ax, [(o[0] + 2 * u * math.cos(math.radians(a)), o[1] + 2 * u * math.sin(math.radians(a))) for a in range(-80, 81, 4)], 'fixe', lw=0.5, dash=True)
disc(ax, M[0], M[1], 1.5, 'sujet'); disc(ax, M1[0], M1[1], 1.5, 'varie'); disc(ax, o[0], o[1], 0.8, 'encre')
text(ax, o[0] + 14, o[1] + 6, r'$\theta$', 'sujet', 's')
text(ax, o[0] + 14, o[1] - 6, r'$-\theta$', 'varie', 's')
text(ax, M[0] + 14, M[1] + 3, r'$M$ (1 ; 1,73)', 'sujet', 's')
text(ax, M1[0] + 15, M1[1] - 3, r'$M_1$ (1 ; $-$1,73)', 'varie', 's')
text(ax, o[0] + 20, o[1] + 3, r'$x$ = 1', 'fixe', 's')
text(ax, 44, 12, r'$\cos(-\theta) = \cos\theta$ : même $x$', 'fixe', 's')
text(ax, 44, 6, r'$\sin(-\theta) = -\sin\theta$ : $y$ opposé', 'varie', 's')
text(ax, 44, 88, 'reflet par l’axe des $x$', 'encre', 'm')
save(fig, '40-036')
