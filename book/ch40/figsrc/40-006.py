import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
from math import pi, cos, sin, radians
fig, ax = canvas(80)
k = 28.0 / 147.1  # mm par million de km
c = (36, 32)
R = lambda t: 149.6 / (1 + 0.017 * cos(t))
pp = lambda r, t: (c[0] + k * r * cos(t), c[1] + k * r * sin(t))
line(ax, [pp(R(t), t) for t in [i * 2 * pi / 500 for i in range(501)]], 'sujet', lw=1.1)
line(ax, [pp(R(0), 0), pp(R(pi), pi)], 'fixe', lw=0.5, dash=True)
t3 = radians(60)
line(ax, [c, pp(R(t3), t3)], 'varie', lw=0.9)
disc(ax, c[0], c[1], 1.8, 'varie')
text(ax, c[0] - 1, c[1] + 5, 'Soleil', 'varie', 's')
disc(ax, *pp(R(0), 0), 1.2, 'resultat')
disc(ax, *pp(R(pi), pi), 1.2, 'resultat')
disc(ax, *pp(R(t3), t3), 1.2, 'resultat')
text(ax, pp(R(0), 0)[0] - 1, c[1] - 5, '147,1', 'resultat', 's')
text(ax, pp(R(pi), pi)[0] + 3, c[1] - 5, '152,2', 'resultat', 's')
line(ax, [pp(0.2 * R(0), t) for t in [radians(60 * i / 30) for i in range(31)]], 'varie', lw=0.8)
text(ax, c[0] + 12, c[1] + 4.5, r'$\theta$', 'varie', 's')
text(ax, c[0] + 8, c[1] + 15, r'$r$', 'varie', 's')
box(ax, 4, 66, 80, 10, 'sujet', label=r'$r=149{,}6\,/\,(1+0{,}017\cos\theta)$', size='m')
text(ax, 62, 6, 'r en millions de km', 'encre', 's')
save(fig, '40-006')
