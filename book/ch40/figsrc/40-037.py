import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# M (2 ; π/3) ; (2 ; 2π/3) = (-1 ; 1,73) reflet par l'axe y ; (-2 ; 2π/3) = (1 ; -1,73) reflet par l'axe x
fig, ax = canvas(88)
o = (44, 46); u = 14
def pt(r, deg): return (o[0] + u * r * math.cos(math.radians(deg)), o[1] + u * r * math.sin(math.radians(deg)))
arrow(ax, (o[0] - 34, o[1]), (o[0] + 37, o[1]), 'fixe', lw=0.9)
arrow(ax, (o[0], o[1] - 32), (o[0], o[1] + 34), 'fixe', lw=0.9)
text(ax, o[0] + 39, o[1] - 3, r'$x$', 'fixe', 's')
text(ax, o[0] + 3, o[1] + 35, r'$y$', 'fixe', 's')
M, A, B = pt(2, 60), pt(2, 120), pt(-2, 120)
line(ax, [pt(-2.2, 120), pt(2.2, 120)], 'fixe', lw=0.7, dash=True)
line(ax, [o, M], 'sujet', lw=1.3)
line(ax, [o, A], 'varie', lw=1.3)
arrow(ax, (o[0] + 0.3, o[1] - 0.5), (B[0] - 0.4, B[1] + 0.6), 'autre', lw=1.5)
line(ax, [M, A], 'fixe', lw=0.8, dash=True)
disc(ax, M[0], M[1], 1.5, 'sujet'); disc(ax, A[0], A[1], 1.5, 'varie'); disc(ax, B[0], B[1], 1.5, 'autre'); disc(ax, o[0], o[1], 0.8, 'encre')
text(ax, M[0] + 14, M[1] + 3, r'$M$ (2 ; 60°)', 'sujet', 's')
text(ax, A[0] - 12, A[1] + 4, r'(2 ; 120°)', 'varie', 's')
text(ax, B[0] + 13, B[1] - 3, r'($-$2 ; 120°)', 'autre', 's')
text(ax, 22, 14, r'(2 ; 120°) = ($-$1 ; 1,73)', 'varie', 's')
text(ax, 22, 9, 'reflet de $M$ par l’axe $y$', 'varie', 's')
text(ax, 66, 14, r'($-$2 ; 120°) = (1 ; $-$1,73)', 'autre', 's')
text(ax, 66, 9, 'reflet de $M$ par l’axe $x$', 'autre', 's')
text(ax, 44, 85, r'$r$ change de signe : autre reflet', 'encre', 'm')
save(fig, '40-037')
