import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(54)
k = 3.2; L = (14, 22); R = (66, 22)
def vec(o, v, role): arrow(ax, o, (o[0] + v[0] * k, o[1] + v[1] * k), role, lw=1.3)
vec(L, (3, 4), 'sujet'); vec(L, (5, 0), 'autre')
vec(R, (-4, 3), 'sujet'); vec(R, (0, 5), 'autre')
text(ax, L[0] + 9.6, L[1] + 16.5, r'$x=(3,\,4)$', 'sujet', 's')
text(ax, L[0] + 16, L[1] - 4, r'$y=(5,\,0)$', 'autre', 's')
text(ax, R[0] - 12.8, R[1] + 13.5, r'$Ax=(-4,\,3)$', 'sujet', 's')
text(ax, R[0] + 1, R[1] + 19.5, r'$Ay=(0,\,5)$', 'autre', 's', ha='left')
arrow(ax, (34, 40), (50, 40), 'varie', lw=1.3)
text(ax, 42, 44.5, r'$A$', 'varie', 'l')
text(ax, 22, 9, r'$\langle x,y\rangle=15$', 'sujet')
text(ax, 66, 9, r'$\langle Ax,Ay\rangle=15$', 'resultat')
text(ax, 44, 9, '=', 'resultat', 'l')
save(fig, '73-086')
