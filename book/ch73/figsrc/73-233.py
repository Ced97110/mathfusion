import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig,ax=canvas(82)
o=(26,42); r=20
ax.add_patch(Circle(o,r,ec=COL['fixe'],fc='none',lw=0.5,zorder=1))
line(ax,[(o[0]-r-4,o[1]),(o[0]+r+4,o[1])],'fixe',lw=0.7,dash=True)
c45=math.cos(math.radians(45))
line(ax,[(o[0]-(r+4)*c45,o[1]-(r+4)*c45),(o[0]+(r+4)*c45,o[1]+(r+4)*c45)],'autre',lw=0.7,dash=True)
Pp=(o[0]+r,o[1]); Q=(o[0],o[1]+r); S=(o[0],o[1]-r)
arrow(ax,Pp,Q,'varie',curve=0.3); arrow(ax,Q,S,'varie')
arrow(ax,Pp,S,'resultat',lw=1.4,curve=-0.35)
for p in (Pp,Q,S): disc(ax,*p,1.1,'sujet')
text(ax,Pp[0]+2,Pp[1]+2.5,r'$(1,0)$','sujet','s',ha='left')
text(ax,Q[0]+3,Q[1]+2,r'$(0,1)$','sujet','s',ha='left')
text(ax,S[0]+3,S[1]-2,r'$(0,-1)$','sujet','s',ha='left')
text(ax,o[0]-8,o[1]-4,'axe 0°','fixe','s')
text(ax,o[0]+12,o[1]+22,'axe 45°','autre','s',ha='left')
text(ax,o[0]+17,o[1]+13,'1','varie','m',weight='bold'); text(ax,o[0]-4,o[1]-8,'2','varie','m',weight='bold')
text(ax,52,70,'1. miroir 90° (axe 45°)','varie','s',ha='left')
text(ax,52,63,'2. miroir 0° (axe 0°)','varie','s',ha='left')
text(ax,52,52,r'$\beta=90°$ puis $\alpha=0$','encre','s',ha='left')
text(ax,52,36,r'$R(\alpha-\beta)$','resultat','m',ha='left')
text(ax,52,29,r'$=R(-90°)$','resultat','s',ha='left')
