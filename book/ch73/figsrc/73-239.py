text(ax,P(1,0)[0],P(1,0)[1]-4,r'$P$','sujet','s')
text(ax,P(0,1)[0]-3,P(0,1)[1]+3.5,r'$(0,1)$','sujet','s',ha='left')
text(ax,P(2,1)[0]+3,P(2,1)[1]+1,r'$(2,1)$','sujet','s',ha='left')
