import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
import math
fig, ax = canvas(56)
O = (44, 8); R = 34
P = lambda deg, r=R: (O[0] + r * math.cos(math.radians(deg)), O[1] + r * math.sin(math.radians(deg)))
line(ax, [P(t) for t in range(0, 181, 3)], 'fixe', lw=1.0)
line(ax, [(O[0] - R - 3, O[1]), (O[0] + R + 3, O[1])], 'fixe', lw=0.8)
line(ax, [(O[0], O[1]), (O[0], O[1] + R + 3)], 'fixe', lw=0.8, dash=True)
p60, p120 = P(60), P(120)
line(ax, [O, p60], 'sujet'); line(ax, [O, p120], 'resultat')
line(ax, [p120, p60], 'varie', lw=0.8, dash=True)
line(ax, [p60, (p60[0], O[1])], 'sujet', lw=0.7, dash=True)
line(ax, [p120, (p120[0], O[1])], 'resultat', lw=0.7, dash=True)
line(ax, [O, (p60[0], O[1])], 'sujet', lw=2.2)
line(ax, [O, (p120[0], O[1])], 'resultat', lw=2.2)
disc(ax, p60[0], p60[1], 1.5, 'sujet'); disc(ax, p120[0], p120[1], 1.5, 'resultat')
line(ax, [P(t, 9) for t in range(0, 61, 3)], 'sujet', lw=0.8)
line(ax, [P(t, 15) for t in range(0, 121, 3)], 'resultat', lw=0.8)
text(ax, P(30, 13)[0], P(30, 13)[1], '60°', 'sujet', 's')
text(ax, P(160, 20)[0], P(160, 20)[1], '120°', 'resultat', 's')
text(ax, p60[0] + 1, O[1] - 3.5, '0,5', 'sujet', 's')
text(ax, p120[0] - 1, O[1] - 3.5, '−0,5', 'resultat', 's')
text(ax, p60[0] + 3, p60[1] + 1, '0,866', 'sujet', 's', ha='left')
text(ax, p120[0] - 3, p120[1] + 1, '0,866', 'resultat', 's', ha='right')
text(ax, O[0], O[1] + R + 6, 'axe vertical', 'fixe', 's')
save(fig, '34-121')
