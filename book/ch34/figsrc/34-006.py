import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(78)
L = 64; fx, fy = 6, 6
end = lambda d: (fx + L*math.cos(math.radians(d)), fy + L*math.sin(math.radians(d)))
pol = lambda r, d: (fx + r*math.cos(math.radians(d)), fy + r*math.sin(math.radians(d)))
def arcl(r, a0, a1, role, dash=False, lw=1.0):
    line(ax, [pol(r, a0 + (a1 - a0)*i/20) for i in range(21)], role, lw=lw, dash=dash)
line(ax, [(fx - 2, fy), (84, fy)], 'fixe', lw=1.2)
e30, e45, e75 = end(30), end(45), end(75)
line(ax, [(fx, fy), e30], 'fixe', lw=1.4)
line(ax, [(fx, fy), e45], 'autre', lw=1.2, dash=True)
line(ax, [(fx, fy), e75], 'sujet', lw=1.6)
for e, role in ((e30, 'fixe'), (e45, 'autre'), (e75, 'sujet')):
    line(ax, [e, (80, e[1])], role, dash=True, lw=0.6)
line(ax, [(68, fy), (68, e45[1])], 'autre', lw=2)
line(ax, [(78, e30[1]), (78, e75[1])], 'varie', lw=2)
arcl(30, 30, 75, 'varie', lw=1.2)
arcl(24, 0, 45, 'autre', dash=True, lw=1.0)
text(ax, *pol(36, 60), '+45°', 'varie', 's')
text(ax, *pol(29, 20), '+45°', 'autre', 's')
text(ax, 71.5, (fy + e45[1])/2, '+0,7071 depuis le sol', 'autre', 's', rot=90)
text(ax, 81.5, (e30[1] + e75[1])/2, '+0,4659 depuis 30°', 'varie', 's', rot=90)
text(ax, e30[0] - 5, e30[1] + 4, '30°', 'fixe', 'm')
text(ax, e45[0] - 6, e45[1] + 3, '45°', 'autre', 'm')
text(ax, e75[0] - 5, e75[1] + 4, '75°', 'sujet', 'm')
text(ax, 65, e30[1] + 2.4, '0,5', 'fixe', 's')
text(ax, 52, e75[1] + 2.4, '0,9659', 'sujet', 's')
text(ax, 38, 2.6, 'échelle de longueur 1 m', 'encre', 's')
save(fig, '34-006')
