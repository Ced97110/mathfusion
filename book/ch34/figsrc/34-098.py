import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
R = 16; c = (30, 30)
g = lambda x, y: (c[0] + R * x, c[1] + R * y)
ax.add_patch(Circle(c, R, ec=COL['fixe'], fc='none', lw=0.8, zorder=1))
line(ax, [g(-1.25, 0), g(1.25, 0)], 'fixe', lw=0.6)
K = g(-1, 0); P = g(0.5, 0.866); F = g(0.5, 0); O = g(0, 0)
poly(ax, [K, F, P], 'sujet')
line(ax, [O, P], 'fixe', lw=0.7)
line(ax, [F, P], 'resultat', lw=2.2)
text(ax, K[0] - 3, K[1] - 2, '$K$'); text(ax, F[0] + 2.5, F[1] - 2.5, '$F$'); text(ax, P[0] + 1, P[1] + 3, '$P$')
text(ax, O[0] - 1, O[1] - 3, '$O$', 'fixe', 's')
text(ax, 55, 50, 'hauteur de $P$ :', 'autre', 's', ha='left')
text(ax, 55, 46.5, '$\\sin 60°$ = 0,866', 'autre', 's', ha='left')
text(ax, 55, 40, 'côté du triangle :', 'sujet', 's', ha='left')
text(ax, 55, 36.5, '2 cos 30° sin 30° = 0,866', 'sujet', 's', ha='left')
arrow(ax, (54, 48), (F[0] + 1.2, 38), 'autre', lw=0.8)
arrow(ax, (54, 38), (F[0] + 1.2, 33), 'sujet', lw=0.8)
text(ax, 44, 4, '$\\sin 2A$ = 2 $\\sin A\\, \\cos A$', 'resultat', 'l')
save(fig, '34-098')
