import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
u = 14; o = (16, 10)
P = lambda a, b: (o[0] + a * u, o[1] + b * u)
line(ax, [P(0, 1), P(1, 1), P(1, 0)], 'fixe', dash=True)
arrow(ax, P(0, 0), P(1, 0), 'sujet', lw=1.4)
arrow(ax, P(0, 0), P(0, 1), 'autre', lw=1.4)
arrow(ax, P(0, 0), P(1, 1), 'resultat', lw=1.4)
text(ax, P(0.5, 0)[0], P(0.5, 0)[1] - 4, r'$x$', 'sujet', 's')
text(ax, P(0, 0.5)[0] - 1, P(0, 0.5)[1], r"$x'$", 'autre', 's', ha='right')
text(ax, P(1, 1)[0] + 1, P(1, 1)[1] + 4, r"$x + x'$", 'resultat', 's', ha='left')
text(ax, 60, 36, r'$B(x, y) = 1$', 'sujet', 's', ha='left')
text(ax, 60, 28, r"$B(x', y) = 2$", 'autre', 's', ha='left')
line(ax, [(60, 23), (85, 23)], 'fixe')
text(ax, 60, 17, r"$B(x{+}x', y) = 3$", 'resultat', 's', ha='left')
text(ax, 60, 9, r'$1 + 2 = 3$', 'resultat', 'm', ha='left')
save(fig, '71-052')
