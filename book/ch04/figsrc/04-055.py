def mw(s, size='l', weight='normal'):
    t=fig.text(0,0,s,fontsize=SIZE[size],fontweight=weight)
    w=t.get_window_extent(fig.canvas.get_renderer()).width
    t.remove(); return w*25.4/fig.dpi
