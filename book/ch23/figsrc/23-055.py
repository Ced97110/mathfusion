arrow(ax, (f(4), 33), (f(-4), 33), 'varie', curve=0.35)
arrow(ax, (f(-3), 27), (f(3), 27), 'varie', curve=0.35)
text(ax, f(4), 50, r'$b=4$', 'sujet', 'm'); text(ax, f(-4), 50, r'$-b=-4$', 'resultat', 'm')
text(ax, f(-3), 9, r'$b=-3$', 'sujet', 'm'); text(ax, f(3), 9, r'$-b=3$', 'resultat', 'm')
