import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
u = 6.2; x0 = 11; y0 = 22; h = 4*u
def P(a, b): return (x0+a*u, y0+b*u)
poly(ax, [P(0, 0), P(6, 0), P(2, 4), P(0, 4)], 'sujet')
poly(ax, [P(8, 4), P(2, 4), P(6, 0), P(8, 0)], 'autre')
text(ax, *P(1.8, 1.2), 'trapèze', 'sujet', 's')
text(ax, *P(5.7, 2.8), 'copie', 'autre', 's')
text(ax, *P(1, 4.5), '2', 'sujet', 's')
text(ax, *P(5, 4.5), '6', 'autre', 's')
text(ax, *P(3, -0.5), '6', 'sujet', 's')
text(ax, *P(7, -0.5), '2', 'autre', 's')
brace(ax, x0, x0+8*u, y0-6, 'resultat', '2 + 6 = 8')
arrow(ax, (x0-4, y0), (x0-4, y0+h), 'fixe', both=True)
text(ax, x0-7.5, y0+h/2, 'h = 4', 'fixe', 's', rot=90)
text(ax, 76, 40, '8 × 4 = 32', 'encre')
text(ax, 76, 31, '32 ÷ 2 = 16', 'encre')
text(ax, 76, 21, 'A = 16 m²', 'resultat', weight='bold')
save(fig, '11-117')
