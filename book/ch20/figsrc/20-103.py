import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
box(ax, 2, 62, 22, 9, 'varie', label=r'$y=x+1$', size='s')
box(ax, 26, 62, 22, 9, 'sujet', label=r'$x+y=3$', size='s')
arrow(ax, (37, 62), (25, 52), 'varie')
text(ax, 38, 57, r'$y$ devient $x+1$', 'varie', 's', ha='left')
box(ax, 2, 42, 46, 9, 'varie', label=r'$x+(x+1)=3$', size='s')
arrow(ax, (25, 42), (25, 33), 'varie')
box(ax, 2, 24, 46, 9, 'varie', label=r'$2x+1=3$', size='s')
arrow(ax, (25, 24), (25, 15), 'varie')
box(ax, 2, 6, 46, 9, 'resultat', label=r'$x=1$, puis $y=2$', size='s')
ox, oy, u = 52, 22, 6.5
m = lambda x, y: (ox + (x + 1) * u, oy + (y + 1) * u)
poly(ax, [m(-1, -1), m(4, -1), m(4, 4), m(-1, 4)], 'fixe', fill=False)
line(ax, [m(-1, 0), m(3, 4)], 'varie', lw=1.3)
line(ax, [m(-1, 4), m(4, -1)], 'sujet', lw=1.3)
S = m(1, 2); disc(ax, S[0], S[1], 1.3, 'resultat')
text(ax, S[0], S[1] - 5, r'$S$', 'resultat', 'm', weight='bold')
text(ax, 68, 62, 'les deux droites', 'fixe', 's')
text(ax, 68, 57, 'se croisent en S', 'resultat', 's')
save(fig, '20-103')
