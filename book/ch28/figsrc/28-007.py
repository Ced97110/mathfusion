import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
def pol(c, r, d): return (c[0] + r * math.cos(math.radians(d)), c[1] + r * math.sin(math.radians(d)))
def arc(ax, c, r, a0, a1, role, lw=0.9, dash=False, n=48): line(ax, [pol(c, r, a0 + (a1 - a0) * i / n) for i in range(n + 1)], role, lw, dash)
def dot(ax, p, role, r=1.0): ax.add_patch(Circle(p, r, ec=COL[role], fc=COL[role], lw=0.5, zorder=4))
def sq(ax, p, ux, uy, s=2.2, role='fixe'): line(ax, [(p[0] + ux * s, p[1]), (p[0] + ux * s, p[1] + uy * s), (p[0], p[1] + uy * s)], role, lw=0.7)

fig, ax = canvas(62)
O = (28, 34)
sp = lambda t: pol(O, 10 + 8 * t / 400, t)
line(ax, [sp(t) for t in range(0, 361, 6)], 'fixe', lw=1.2)
line(ax, [sp(t) for t in range(360, 401, 4)], 'varie', lw=1.6)
arrow(ax, sp(396), sp(400), 'varie')
P = pol(O, 26, 40)
line(ax, [O, P], 'sujet', lw=1.8)
line(ax, [O, (O[0] + 22, O[1])], 'fixe', lw=0.9)
dot(ax, O, 'fixe'); dot(ax, P, 'sujet', 1.4)
text(ax, 52, 26, 'un tour : 360°', 'fixe', ha='left')
text(ax, 52, 19, '+ 40° encore', 'varie', ha='left')
text(ax, 52, 12, '= 400°', 'sujet', 'l', ha='left', weight='bold')
text(ax, 52, 5, 'même place que 40°', 'encre', ha='left')
save(fig, '28-007')
