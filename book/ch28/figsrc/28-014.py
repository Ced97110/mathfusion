line(ax, [O, P], 'resultat', lw=2.0)
arc(ax, O, 9, 0, 126, 'varie'); arrow(ax, pol(O, 9, 124), pol(O, 9, 130), 'varie')
dot(ax, O, 'fixe', 1.0); dot(ax, A, 'sujet', 1.5); dot(ax, P, 'resultat', 1.5)
text(ax, 30.5, 24.5, r'$O$'); text(ax, 64, 31, r'$A$', 'sujet', 'l')
