import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
def pol(c, r, d): return (c[0] + r * math.cos(math.radians(d)), c[1] + r * math.sin(math.radians(d)))
def arc(ax, c, r, a0, a1, role, lw=0.9, dash=False, n=48): line(ax, [pol(c, r, a0 + (a1 - a0) * i / n) for i in range(n + 1)], role, lw, dash)
def dot(ax, p, role, r=1.0): ax.add_patch(Circle(p, r, ec=COL[role], fc=COL[role], lw=0.5, zorder=4))
def sq(ax, p, ux, uy, s=2.2, role='fixe'): line(ax, [(p[0] + ux * s, p[1]), (p[0] + ux * s, p[1] + uy * s), (p[0], p[1] + uy * s)], role, lw=0.7)

fig, ax = canvas(64)
O = (54, 32); R = 24; P = pol(O, R, 130); N = (P[0], O[1])
arrow(ax, (10, 32), (84, 32), 'fixe', lw=0.7); arrow(ax, (54, 6), (54, 60), 'fixe', lw=0.7)
arc(ax, O, R, 0, 360, 'sujet', lw=1.2, n=120)
line(ax, [O, P], 'sujet', lw=1.0)
line(ax, [O, N], 'varie', lw=2.2)
line(ax, [N, P], 'resultat', lw=2.2)
arc(ax, O, 7, 0, 130, 'fixe')
dot(ax, P, 'sujet', 1.4); dot(ax, O, 'fixe', 1.0); dot(ax, N, 'varie', 1.2)
text(ax, 57.5, 28.5, r'$O$'); text(ax, N[0], N[1] - 4, r'$N$', 'varie')
text(ax, P[0] - 1.5, P[1] + 3.5, r'$P$', 'sujet')
text(ax, 55, 41, r'$\theta$', 'fixe', 's', ha='left')
text(ax, 44, 24, r'$ON=\cos\theta<0$', 'varie')
text(ax, 34.5, 47, r'$NP=\sin\theta>0$', 'resultat', ha='right')
save(fig, '28-011')
