import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
R = 26; O = (40, 30)
disc(ax, O[0], O[1], R, 'sujet')
v = (O[0]+R, O[1])
w2 = (O[0]+R*math.cos(math.radians(144)), O[1]+R*math.sin(math.radians(144)))
Q = (v[0]+w2[0]-O[0], v[1]+w2[1]-O[1])
line(ax, [v, Q, w2], 'fixe', dash=True)
arrow(ax, O, v, 'sujet', lw=1.3)
arrow(ax, O, w2, 'varie', lw=1.3)
disc(ax, Q[0], Q[1], 1.6, 'limite')
disc(ax, O[0], O[1], 1.0, 'encre')
text(ax, v[0]-9, O[1]-3, r'$v$', 'sujet', 'l')
text(ax, w2[0]-4, w2[1]+3.5, r'$\rho^2(v)$', 'varie', 'm')
text(ax, Q[0]+5, Q[1]+3, r'$Q$', 'limite', 'l')
text(ax, O[0]-3.5, O[1]-3, r'$O$', 'encre', 's')
arrow(ax, (O[0]+7, O[1]), (O[0]+7*math.cos(math.radians(144)), O[1]+7*math.sin(math.radians(144))), 'varie', curve=0.4, lw=0.7)
text(ax, O[0]-5, O[1]+9.5, '144°', 'varie', 's')
text(ax, 64, 5, r'$Q$ dans le disque', 'limite', 's')
save(fig, '74-133')
