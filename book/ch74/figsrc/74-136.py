poly(ax, [O, v, r], 'fixe')
arrow(ax, O, v, 'sujet', lw=1.2)
arrow(ax, O, r, 'varie', lw=1.2)
line(ax, [v, r], 'resultat', lw=1.6)
text(ax, v[0]+5, v[1]-3, r'$v$', 'sujet', 'l')
text(ax, r[0]+4, r[1]+4, r'$\rho(v)$', 'varie', 'm')
