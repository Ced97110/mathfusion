import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(52)
ox, oy, u = 10, 12, 11
P = lambda x, y: (ox + x * u, oy + y * u)
line(ax, [P(-0.3, 0), P(5.5, 0)], 'fixe', dash=True)
text(ax, P(5.5, 0)[0] + 1.5, oy, r'axe de $A$', 'fixe', 's', ha='left')
line(ax, [P(-0.3, 1), P(5.5, 1)], 'resultat', lw=1.3)
text(ax, P(5.5, 1)[0] + 1.5, P(0, 1)[1], r'$D$', 'resultat', 'l', ha='left')
arrow(ax, P(0, 0), P(5, 0), 'varie', lw=1.3)
arrow(ax, P(5, 0), P(5, 2), 'varie', lw=1.3)
arrow(ax, P(0, 0), P(4.9, 1.95), 'sujet', lw=1.3)
text(ax, P(2.5, 0)[0], P(0, 0)[1] - 3.2, r'$b_1$ : le long de l’axe', 'varie', 's')
text(ax, P(5, 1.5)[0] + 2, P(0, 1.5)[1], r'$b_2$ : en travers', 'varie', 's', ha='left')
text(ax, P(1.6, 1.4)[0] - 5, P(0, 1.65)[1] + 2.5, r'$b$', 'sujet', 'm')
disc(ax, *P(0, 1), 1.1, 'sujet'); disc(ax, *P(5, 1), 1.1, 'resultat')
text(ax, P(0, 1)[0], P(0, 1)[1] + 3.2, r'$(0\,;\,1)$', 'sujet', 's')
text(ax, P(5, 1)[0] - 4.5, P(5, 1)[1] - 3.2, r'$(5\,;\,1)$', 'resultat', 's')
text(ax, 44, 48, r'$b=b_1+b_2$, $D$ décalée de $b_2/2$', 'encre', 's')
save(fig, '74-052')
