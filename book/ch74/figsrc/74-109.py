import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(70)
c = (44, 43); u = 8.5
P = lambda a, b: (c[0]+a*u, c[1]+b*u)
line(ax, [P(0, -4.5), P(0, 3)], 'fixe', dash=True)
line(ax, [P(-4, -4), P(2.6, 2.6)], 'fixe', dash=True)
text(ax, P(0, 3)[0]-9, P(0, 3)[1], 'axe vertical', 'fixe', 's')
text(ax, P(2.6, 2.6)[0]+8, P(2.6, 2.6)[1]-1, 'diagonale', 'fixe', 's')
arrow(ax, (P(3,1)[0]-2, P(3,1)[1]), (P(-3,1)[0]+2, P(-3,1)[1]), 'varie', lw=1.3)
arrow(ax, (P(-3,1)[0]+1, P(-3,1)[1]-2), (P(1,-3)[0]-2, P(1,-3)[1]+1), 'varie', lw=1.3)
arrow(ax, (P(3,1)[0]-1, P(3,1)[1]-2), (P(1,-3)[0]+2, P(1,-3)[1]), 'resultat', lw=1.3, curve=0.3)
disc(ax, *P(3, 1), 1.6, 'sujet'); disc(ax, *P(-3, 1), 1.6, 'varie'); disc(ax, *P(1, -3), 1.6, 'resultat')
text(ax, P(3,1)[0]+3, P(3,1)[1]+4, r'$(3,1)$', 'sujet', 's')
text(ax, P(-3,1)[0]-2, P(-3,1)[1]+4, r'$(-3,1)$', 'varie', 's')
text(ax, P(1,-3)[0]+9, P(1,-3)[1]-3, r'$(1,-3)$', 'resultat', 's')
text(ax, P(0, 1)[0]+0, P(0, 1)[1]+3.2, r'$s_1$', 'varie', 's')
text(ax, P(-1.3, -1.2)[0]-3, P(-1.3, -1.2)[1]-2, r'$s_2$', 'varie', 's')
text(ax, P(3.2, -1.5)[0]+1, P(3.2, -1.5)[1], r'$s_2\circ s_1$', 'resultat', 's')
save(fig, '74-109')
