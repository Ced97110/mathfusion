import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(62)
s, x0, y0 = 40, 5, 12
C = lambda u, v: (x0 + u*s, y0 + v*s)
def dia(x, y): poly(ax, [(x-1.9, y), (x, y+2.6), (x+1.9, y), (x, y-2.6)], 'sujet')
poly(ax, [C(0,0), C(1,0), C(1,1), C(0,1)], 'fixe', fill=False)
for p in [(0,0),(1,0),(1,1),(0,1)]: dia(*C(*p))
cx, cy = C(.5, .5); disc(ax, cx, cy, 2.2, 'resultat')
line(ax, [C(0,.5), C(.5,0)], 'resultat', lw=1.4, dash=True)
arrow(ax, C(0,0), (cx-2.4, cy-2.4), 'limite')
a, b = C(.04, .4), C(.4, .04)
arrow(ax, a, b, 'varie')
text(ax, 52, 54, 'retournement seul :', 'limite', 's', ha='left')
text(ax, 52, 50, 'losange sur disque', 'limite', 's', ha='left')
text(ax, 52, 24, 'puis glissement', 'varie', 's', ha='left')
text(ax, 52, 20, 'de 7,1 cm', 'varie', 's', ha='left')
line(ax, [(52, 36), (57, 36)], 'resultat', lw=1.4, dash=True)
text(ax, 59, 36, 'axe glissé', 'resultat', 's', ha='left')
text(ax, 25, 4, 'carreau de 10 cm', 'fixe', 's')
save(fig, '74-172')
