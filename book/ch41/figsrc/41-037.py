import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
# 41-037 : AB = ⟨x2 − x1, y2 − y1⟩ ; A (1 ; 2), B (4 ; 6) -> ⟨4 − 1, 6 − 2⟩ = ⟨3 ; 4⟩ (8 mm par unité)
fig, ax = canvas(74)
s = 8.0
O = (8, 8)
pt = lambda x, y: (O[0] + x * s, O[1] + y * s)
A = pt(1, 2); B = pt(4, 6); C = pt(4, 2)
arrow(ax, O, (O[0] + 5.6 * s, O[1]), 'fixe', lw=0.6)
arrow(ax, O, (O[0], O[1] + 7.4 * s), 'fixe', lw=0.6)
line(ax, [A, C], 'resultat', lw=1.6, dash=True)
line(ax, [C, B], 'resultat', lw=1.6, dash=True)
arrow(ax, A, B, 'sujet', lw=2.0)
disc(ax, A[0], A[1], 1.1, 'encre'); disc(ax, B[0], B[1], 1.1, 'encre')
text(ax, A[0] - 2.5, A[1] - 3.5, 'A (1 ; 2)', 'encre', 's', ha='right')
text(ax, B[0] + 2.5, B[1] + 2.5, 'B (4 ; 6)', 'encre', 's', ha='left')
text(ax, (A[0] + C[0]) / 2, A[1] - 3.5, '4 − 1 = 3', 'resultat', 's')
text(ax, C[0] + 2.5, (C[1] + B[1]) / 2, '6 − 2 = 4', 'resultat', 's', ha='left')
text(ax, 21.5, 48, r'$\langle$3 ; 4$\rangle$', 'sujet', 'l', weight='bold')
box(ax, 55, 22, 30, 10, 'varie', label='arrivée − départ', size='s')
save(fig, '41-037')
