import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(70)
ox, oy, s = 40, 24, 6.0
P = lambda x, y: (ox + x * s, oy + y * s)
# droite perpendiculaire à v = <4, 2> : direction <-1, 2> (le « miroir »)
line(ax, [P(1.4, -2.8), P(-2, 4)], 'fixe', lw=0.8, dash=True)
text(ax, P(-2, 4)[0] - 4, P(-2, 4)[1] + 4, r'droite $\perp\ v$', 'fixe', 's')
arrow(ax, P(0, 0), P(4, 2), 'autre', lw=1.4)
arrow(ax, P(0, 0), P(1, 3), 'sujet', lw=1.6)
arrow(ax, P(0, 0), P(2, 1), 'varie', lw=1.8)
arrow(ax, P(0, 0), P(-3, 1), 'resultat', lw=1.6)
arrow(ax, P(1, 3), P(-3, 1), 'varie', lw=0.9)
text(ax, P(4, 2)[0] - 2, P(4, 2)[1] + 5, r'$v=\langle 4,\ 2\rangle$', 'autre', 's')
text(ax, P(1, 3)[0], P(1, 3)[1] + 5, r'$u=\langle 1,\ 3\rangle$', 'sujet', 's')
text(ax, P(2, 1)[0] + 6, P(2, 1)[1] - 6, r'$\langle 2,\ 1\rangle$', 'varie', 's')
text(ax, P(-3, 1)[0] - 4, P(-3, 1)[1] - 5, r'$\langle -3,\ 1\rangle$', 'resultat', 's')
text(ax, 46, 64, 'on retire 2 fois la projection', 'varie', 's')
text(ax, 44, 7, r'résultat $=u-2\times\langle 2,\ 1\rangle=\langle -3,\ 1\rangle$', 'resultat', 's')
save(fig, '41-165')
