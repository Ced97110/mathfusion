import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
k = 9.0
O = (30, 12)
u, v = (1, 3), (4, 2)
mv = (-v[0], -v[1])
r = (u[0] - v[0], u[1] - v[1])
assert r == (-3, 1)
T = lambda q, d=(0, 0): (O[0] + k * q[0] + d[0], O[1] + k * q[1] + d[1])
arrow(ax, T(v), T(u), 'resultat', lw=1.2)
arrow(ax, T(u), T(r), 'autre', lw=1.4)
arrow(ax, O, T(r), 'resultat', lw=1.9)
arrow(ax, O, T(u), 'sujet', lw=1.9)
arrow(ax, O, T(v), 'autre', lw=1.9)
text(ax, T(u)[0] - 1, T(u)[1] + 4, r'$u=\langle 1;\ 3\rangle$', 'sujet', 's')
text(ax, T(v)[0] + 2, T(v)[1] - 3, r'$v=\langle 4;\ 2\rangle$', 'autre', 's', ha='left')
text(ax, 3, 6, r'$u-v=\langle -3;\ 1\rangle$', 'resultat', 's', ha='left')
text(ax, 16, 38, r'$-v=\langle -4;\ -2\rangle$', 'autre', 's')
text(ax, 62, 46, 'du bout de $v$', 'resultat', 's', ha='left')
text(ax, 62, 42, 'au bout de $u$', 'resultat', 's', ha='left')
text(ax, 44, 52, r'$u+(-v)=\langle 1-4;\ 3-2\rangle$', 'encre', 's')
