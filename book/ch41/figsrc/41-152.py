import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
s = 2.5
# haut : v dans le même sens que u ; bas : v de sens opposé (échelle identique sur les deux axes)
o1 = (8, 52)
arrow(ax, o1, (o1[0] + 6 * s, o1[1] + 8 * s), 'autre', lw=1.3)
arrow(ax, o1, (o1[0] + 3 * s, o1[1] + 4 * s), 'sujet', lw=1.6)
text(ax, 37, 72, r'$u=\langle 3,\ 4\rangle$', 'sujet', 's')
text(ax, 37, 66, r'$v=\langle 6,\ 8\rangle$', 'autre', 's')
box(ax, 54, 58, 32, 16, 'resultat')
text(ax, 70, 69, r'$u\cdot v=50$', 'resultat', 's')
text(ax, 70, 63, r'$=5\times 10$', 'resultat', 's')
text(ax, 24, 49, 'même sens', 'encre', 's')
text(ax, 14, 18, 'sens opposé', 'encre', 's')
o2 = (38, 24)
arrow(ax, o2, (o2[0] - 6 * s, o2[1] - 8 * s), 'autre', lw=1.3)
arrow(ax, o2, (o2[0] + 3 * s, o2[1] + 4 * s), 'sujet', lw=1.6)
text(ax, 68, 38, r'$u=\langle 3,\ 4\rangle$', 'sujet', 's')
text(ax, 68, 32, r'$v=\langle -6,\ -8\rangle$', 'autre', 's')
box(ax, 54, 8, 32, 16, 'resultat')
text(ax, 70, 19, r'$u\cdot v=-50$', 'resultat', 's')
text(ax, 70, 13, r'$=-5\times 10$', 'resultat', 's')
save(fig, '41-152')
