import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
k = 3.4
O = (6, 8)
m, u, v = 2, (1, 3), (4, 2)
mu, mv = (m * u[0], m * u[1]), (m * v[0], m * v[1])
s = (u[0] + v[0], u[1] + v[1])
ms = (m * s[0], m * s[1])
assert (mu[0] + mv[0], mu[1] + mv[1]) == ms == (10, 10)
T = lambda q: (O[0] + k * q[0], O[1] + k * q[1])
arrow(ax, O, T(ms), 'resultat', lw=1.8)
arrow(ax, O, T(mu), 'sujet', lw=1.6)
arrow(ax, T(mu), T(ms), 'autre', lw=1.6)
text(ax, 24, 47, r'$2(u+v)=\langle 10;\ 10\rangle$', 'resultat', 's', ha='left')
text(ax, T(mu)[0] - 2, T(mu)[1] + 3, r'$2u=\langle 2;\ 6\rangle$', 'sujet', 's', ha='left')
text(ax, T(mu)[0] + 14, T(mu)[1] - 7, r'$2v=\langle 8;\ 4\rangle$', 'autre', 's', ha='left')
box(ax, 54, 22, 32, 9, 'fixe', label=r'$2(1+4)=10$', size='s')
box(ax, 54, 10, 32, 9, 'fixe', label=r'$2(3+2)=10$', size='s')
text(ax, 70, 35, 'composante par composante', 'fixe', 's')
save(fig, '41-065')
