import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(64)
t = math.radians(35); c, s = math.cos(t), math.sin(t)
ox, oy, R = 24, 32, 22
disc(ax, ox, oy, R, 'fixe', fill=False)
line(ax, [(2, oy), (47, oy)], 'fixe')
P = (ox + R * c, oy + R * s); Hh = (P[0], oy); A = (ox + R, oy)
poly(ax, [(ox, oy), Hh, P], 'fixe')
line(ax, [(ox, oy), Hh], 'autre', lw=1.6)
line(ax, [Hh, P], 'varie', lw=1.6)
line(ax, [(ox, oy), P], 'sujet', lw=1.6)
line(ax, [(Hh[0] - 1.8, oy), (Hh[0] - 1.8, oy + 1.8), (Hh[0], oy + 1.8)], 'fixe', lw=0.6)
arc = [(ox + 7 * math.cos(math.radians(a)), oy + 7 * math.sin(math.radians(a))) for a in range(0, 36)]
line(ax, arc, 'fixe', lw=0.8)
text(ax, ox + 11.5, oy + 3.2, r'$\theta$', 'fixe', 's')
text(ax, ox - 2.5, oy - 2.8, '$O$', 'encre', 's'); text(ax, A[0] + 2.6, oy - 2.8, '$A$', 'encre', 's')
text(ax, P[0] - 0.5, P[1] + 3, '$P$', 'sujet', 's'); text(ax, Hh[0] + 0.4, oy - 2.8, '$H$', 'encre', 's')
text(ax, ox + 9.5, oy - 3.2, r'$\cos\theta$', 'autre', 's')
text(ax, Hh[0] + 6.2, oy + 7, r'$\sin\theta$', 'varie', 's')
text(ax, ox + 5.2, oy + 9.8, '1', 'sujet', 's', weight='bold')
text(ax, 71, 46, r'$\sin^2\theta$', 'varie', 'l')
text(ax, 71, 38, r'$+\ \cos^2\theta$', 'autre', 'l')
text(ax, 71, 30, '= 1', 'resultat', 'l', weight='bold')
text(ax, 71, 22, 'à 35°', 'fixe', 's')
save(fig, '31-067')
