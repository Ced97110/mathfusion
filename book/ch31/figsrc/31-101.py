import numpy as np
fig, ax = canvas(62)
text(ax, 22, 58, '35°', 'encre', 'l', weight='bold'); text(ax, 66, 58, '90°', 'encre', 'l', weight='bold')
line(ax, [(44, 6), (44, 56)], 'fixe', dash=True)
r = 9; t = np.radians(35)
O = (14, 38); disc(ax, *O, r, 'fixe', fill=False)
T = (O[0] + r, O[1] + r * np.tan(t))
line(ax, [(T[0], O[1] - 4), (T[0], O[1] + 11)], 'fixe')
line(ax, [O, T], 'sujet', lw=1.3); disc(ax, *T, 0.9, 'resultat')
