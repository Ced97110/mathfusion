for v in (-90, 90): disc(ax, f(v), 33, 1.8, 'limite', fill=False)
text(ax, 44, 47, r'$\tan\theta=2\sin\theta$ : 5 solutions', 'resultat', 's')
text(ax, f(-90) - 2, 40, "tan n'existe pas", 'limite', 's'); text(ax, f(90) + 2, 40, "tan n'existe pas", 'limite', 's')
