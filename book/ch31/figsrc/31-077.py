import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(42)
ox, oy, R = 8, 6, 22
t = math.radians(30)
B = (ox, oy + R); S = (ox + R / math.tan(t), oy + R)
line(ax, [(ox + R * math.cos(math.radians(a)), oy + R * math.sin(math.radians(a))) for a in range(0, 91, 2)], 'fixe', lw=0.9)
line(ax, [(ox, oy), (ox + R + 6, oy)], 'fixe', lw=0.7)
poly(ax, [(ox, oy), B, S], 'sujet')
line(ax, [(ox, oy), B], 'sujet', lw=1.8); line(ax, [B, S], 'varie', lw=1.8); line(ax, [(ox, oy), S], 'resultat', lw=1.8)
line(ax, [(ox - 5, B[1]), (S[0] + 4, B[1])], 'fixe', lw=0.7)
line(ax, [(ox, oy + 1.8), (ox + 1.8, oy + 1.8), (ox + 1.8, oy)], 'fixe', lw=0.5)
line(ax, [(ox + 1.8, B[1]), (ox + 1.8, B[1] - 1.8), (ox, B[1] - 1.8)], 'fixe', lw=0.6)
line(ax, [(ox + 8 * math.cos(math.radians(a)), oy + 8 * math.sin(math.radians(a))) for a in range(0, 31)], 'fixe', lw=0.8)
text(ax, ox + 12, oy + 2.2, r'$\theta$', 'fixe', 's')
text(ax, ox - 3, oy + 11, '1', 'sujet', 's', weight='bold')
text(ax, (B[0] + S[0]) / 2 - 3, B[1] + 3.5, r'$\mathrm{cotan}\,\theta$', 'varie', 's')
text(ax, ox + 21, oy + 8.5, r'$\mathrm{cosec}\,\theta$', 'resultat', 's')
text(ax, B[0] - 3.5, B[1] + 3, '$B$', 'encre', 's'); text(ax, S[0] + 2.5, S[1] + 3.5, '$S$', 'resultat', 's'); text(ax, ox - 2, oy - 2, '$O$', 'encre', 's')
text(ax, 66, 21, r'$1+\mathrm{cotan}^2\theta$', 'encre', 's'); text(ax, 66, 16, r'$=\mathrm{cosec}^2\theta$', 'encre', 's')
text(ax, 66, 9, '30° : 1 + 3 = 4', 'resultat', 's')
save(fig, '31-077')
