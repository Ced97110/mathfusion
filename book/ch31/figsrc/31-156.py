import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
def arc(ax, c, r, a0, a1, role="fixe", lw=0.9, n=60):
    line(ax, [(c[0] + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), c[1] + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)], role, lw)
fig, ax = canvas(68)
r = 30.0; O = (14, 11)
th = math.radians(35); c, s = math.cos(th), math.sin(th)
arc(ax, O, r, 0, 90, 'fixe', 0.8)
line(ax, [O, (O[0] + r + 12, O[1])], 'fixe', 0.5); line(ax, [O, (O[0], O[1] + 52)], 'fixe', 0.5)
P = (O[0] + r * c, O[1] + r * s); H_ = (P[0], O[1]); T = (O[0] + r / c, O[1]); S = (O[0], O[1] + r / s)
line(ax, [S, T], 'fixe', 0.7); line(ax, [O, P], 'fixe', 0.7)
line(ax, [O, H_], 'sujet', 2.0); line(ax, [H_, P], 'sujet', 2.0)
line(ax, [(O[0], O[1] - 3), (T[0], O[1] - 3)], 'autre', 2.0)
line(ax, [(O[0] - 3, O[1]), (O[0] - 3, S[1])], 'autre', 2.0)
disc(ax, *P, 1.2, 'fixe')
text(ax, O[0] + 9, O[1] + 3, 'OH 0,8192', 'sujet', 's')
text(ax, (O[0] + T[0]) / 2, O[1] - 6.5, 'OT 1,2208', 'autre', 's')
text(ax, P[0] + 2, O[1] + 6, 'HP 0,5736', 'sujet', 's', ha='left')
text(ax, O[0] + 3, S[1] + 0.5, 'OS 1,7434', 'autre', 's', ha='left')
text(ax, 71, 52, 'OH × OT = 1', 'resultat', 'm'); text(ax, 71, 44, 'HP × OS = 1', 'resultat', 'm')
text(ax, 71, 36, 'angle de 35°', 'fixe', 's')
save(fig, '31-156')
