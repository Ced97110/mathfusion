import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(56)
th = math.radians(35); R = 34; O = (6, 10)
P = (O[0] + R * math.cos(th), O[1] + R * math.sin(th))
ang = [math.radians(a) for a in range(0, 66)]
line(ax, [(O[0] + R * math.cos(a), O[1] + R * math.sin(a)) for a in ang], 'fixe')
line(ax, [O, (O[0] + R + 2, O[1])], 'fixe')
line(ax, [O, P], 'sujet', lw=1.6)
line(ax, [O, (P[0], O[1])], 'resultat', lw=1.6)
line(ax, [(P[0], O[1]), P], 'resultat', lw=1.6)
disc(ax, P[0], P[1], 1.4, 'sujet')
line(ax, [(O[0] + 9 * math.cos(a), O[1] + 9 * math.sin(a)) for a in [math.radians(k) for k in range(0, 36)]], 'varie', lw=1.2)
text(ax, P[0] + 2, P[1] + 3.5, r'$P$', 'sujet', 'l', ha='left')
text(ax, (O[0] + P[0]) / 2, O[1] - 3.2, 'cos = 0,8192', 'resultat', 's')
text(ax, P[0] - 1.6, O[1] + 5.0, 'sin = 0,5736', 'resultat', 's', ha='right')
box(ax, 47, 36, 38, 14, 'varie', label=None)
text(ax, 66, 46, r'$35^\circ$', 'varie', 'l')
text(ax, 66, 40, '0,6109 radian', 'varie', 'm')
text(ax, 66, 24, 'même point', 'sujet', 'm')
text(ax, 66, 19, 'mêmes sin et cos', 'resultat', 'm')
save(fig, '31-082')
