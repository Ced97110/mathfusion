import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
def arc(c,R,a0,a1,n=60): return [(c[0]+R*math.cos(a0+(a1-a0)*i/n), c[1]+R*math.sin(a0+(a1-a0)*i/n)) for i in range(n+1)]
fig,ax=canvas(66)
O=(10,8); R=28; A=(O[0]+R,O[1])
line(ax,arc(O,R,0,math.pi/2),'sujet',lw=1.1)
line(ax,[O,A],'fixe')
line(ax,[(A[0],O[1]),(A[0],60)],'fixe',lw=1.0)
a=math.radians(45); P1=(O[0]+R*math.cos(a),O[1]+R*math.sin(a)); T1=(A[0],O[1]+R*math.tan(a))
line(ax,[O,T1],'varie',lw=1.0)
disc(ax,T1[0],T1[1],1.1,'varie')
text(ax,T1[0]+4,T1[1]+1.5,r'$T$','varie')
P2=(O[0],O[1]+R)
line(ax,[O,(O[0],60)],'resultat',lw=1.2,dash=False)
disc(ax,P2[0],P2[1],1.1,'resultat')
text(ax,O[0]-3.5,P2[1],r'$P$','resultat')
text(ax,O[0]-3,O[1]-2.5,r'$O$'); text(ax,A[0],A[1]-3,r'$A$')
text(ax,26,62,'45° : $T$ existe','varie','s')
text(ax,63,50,r'90° : $OP$ et $AT$','resultat','s')
text(ax,63,45,'ne se coupent pas','resultat','s')
box(ax,50,22,36,12,'fixe',label=r'$\tan 90°=\dfrac{\sin 90°}{\cos 90°}=\dfrac{1}{0}$',size='s')
text(ax,68,17,'non définie','encre','s')
save(fig,'29-128')
