import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(64)
ox, oy, k = 6, 6, 8.5
P = lambda a, b: (ox + a * k, oy + b * k)
arrow(ax, P(-0.3, 0), P(5, 0), 'fixe', lw=0.5)
arrow(ax, P(0, -0.3), P(0, 6.4), 'fixe', lw=0.5)
line(ax, [P(0, 0), P(3.15, 6.3)], 'sujet', lw=1.6)
line(ax, [P(0, 2), P(4.6, 2)], 'limite', lw=1.2)
line(ax, [P(0, 4), P(4.6, 4)], 'limite', lw=0.7, dash=True)
for pt, role in [((0, 0), 'sujet'), ((1, 2), 'sujet'), ((2, 4), 'sujet')]:
    disc(ax, *P(*pt), 1.1, role)
disc(ax, *P(3, 6), 1.1, 'resultat')
disc(ax, *P(2, 2), 1.1, 'limite')
disc(ax, *P(3, 4), 1.1, 'limite', fill=False)
text(ax, P(1, 2)[0] - 2, P(1, 2)[1] + 2.5, '(1, 2)', 'sujet', 's', ha='right')
text(ax, P(2, 4)[0] - 2, P(2, 4)[1] + 2.5, '(2, 4)', 'sujet', 's', ha='right')
text(ax, P(3, 6)[0] + 2, P(3, 6)[1], '(3, 6)', 'resultat', 's', ha='left')
text(ax, P(0, 0)[0] + 2.5, P(0, 0)[1] - 2.5, '(0, 0)', 'sujet', 's', ha='left')
text(ax, P(2, 2)[0], P(2, 2)[1] - 3, '(2, 2)', 'limite', 's')
text(ax, P(3, 4)[0] + 2, P(3, 4)[1] - 3, '(3, 4)', 'limite', 's', ha='left')
text(ax, P(3.9, 2)[0], P(3.9, 2)[1] + 2.5, 'hauteur 2', 'limite', 's')
text(ax, P(4.0, 4)[0], P(4.0, 4)[1] + 2.5, 'hauteur 4', 'limite', 's')
box(ax, 54, 38, 32, 18, 'resultat', label='stable : la somme\nreste dans la droite', size='s')
box(ax, 54, 10, 32, 18, 'limite', label='pas stable : la somme\nsort de la partie', size='s')
save(fig, '58-118')
