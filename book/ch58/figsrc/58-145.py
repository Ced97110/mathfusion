import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
u, O = 6.0, (32, 8)
P = lambda x, y, z: iso(x, y, z, O, u)
# la flèche : 3 vers la droite (i), 2 vers l'avant (j), 5 vers le haut (k)
c = (3, 2, 5)
for k in range(0, 4):
    line(ax, [P(k, 0, 0), P(k, 2, 0)], 'fixe', lw=0.3, dash=True)
for k in range(0, 3):
    line(ax, [P(0, k, 0), P(3, k, 0)], 'fixe', lw=0.3, dash=True)
arrow(ax, P(0, 0, 0), P(3, 0, 0), 'sujet', lw=1.4)
arrow(ax, P(3, 0, 0), P(3, 2, 0), 'autre', lw=1.4)
arrow(ax, P(3, 2, 0), P(3, 2, 5), 'varie', lw=1.4)
arrow(ax, P(0, 0, 0), P(3, 2, 5), 'resultat', lw=1.6)
disc(ax, *P(0, 0, 0), 1.0, 'encre')
text(ax, O[0] - 3, O[1] - 3, r'$O$', 'encre', 's')
q = P(1.5, 0, 0); text(ax, q[0] + 2, q[1] - 4, r'$3\,i$', 'sujet', 'm')
q = P(3, 1, 0); text(ax, q[0] + 5.5, q[1] - 1, r'$2\,j$', 'autre', 'm')
q = P(3, 2, 2.5); text(ax, q[0] + 5.5, q[1], r'$5\,k$', 'varie', 'm')
q = P(1.5, 1, 2.5); text(ax, q[0] - 8, q[1] + 1, r'$3i+2j+5k$', 'resultat', 'm')
text(ax, 14, 66, r'$i$ : 1 vers la droite', 'sujet', 's', ha='left')
text(ax, 14, 62, r'$j$ : 1 vers l’avant', 'autre', 's', ha='left')
text(ax, 14, 58, r'$k$ : 1 vers le haut', 'varie', 's', ha='left')
save(fig, '58-145')
