poly(ax, [pt(-.4, -.4), pt(1.4, -.4), pt(1.4, 1.4), pt(-.4, 1.4)], 'fixe')
line(ax, [pt(1, 0), pt(1, 1), pt(0, 1)], 'resultat', lw=0.8, dash=True)
