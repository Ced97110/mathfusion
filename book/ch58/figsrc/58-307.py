import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(64)
u = 6.0; O = (30, 30)
A = (1, 2, 1); B = (0, 1, -1)
def pt(s, t):
    return iso(s * A[0] + t * B[0], s * A[1] + t * B[1], s * A[2] + t * B[2], O, u)
poly(ax, [pt(-.4, -.4), pt(1.4, -.4), pt(1.4, 1.4), pt(-.4, 1.4)], 'sujet')
line(ax, [pt(1, 0), pt(1, 1), pt(0, 1)], 'fixe', lw=0.8, dash=True)
arrow(ax, pt(0, 0), pt(1, 0), 'sujet', lw=1.6)
arrow(ax, pt(0, 0), pt(0, 1), 'varie', lw=1.6)
disc(ax, O[0], O[1], 1.0, 'encre')
disc(ax, pt(1, 1)[0], pt(1, 1)[1], 1.1, 'resultat')
text(ax, O[0] + 2.6, O[1] - 2.4, 'O', 'encre', 's')
text(ax, pt(1, 0)[0] - 2.5, pt(1, 0)[1] + 1.5, 'a', 'sujet', 's')
text(ax, pt(0, 1)[0] - 2.5, pt(0, 1)[1] - 1.5, 'b', 'varie', 's')
text(ax, pt(1, 1)[0] - 7, pt(1, 1)[1] - 1, 'a + b', 'resultat', 's')
text(ax, 21, 59, 'plan : s·a + t·b', 'sujet', 's')
