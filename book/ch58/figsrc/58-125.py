import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(72)
n = lambda v: str(v).replace('-', '−')
t3 = lambda t: '(' + ', '.join(n(v) for v in t) + ')'
a, b = (1, 2, 1), (0, 1, -1)
ma = tuple(2 * v for v in a); mb = tuple(3 * v for v in b)
tot = tuple(x + y for x, y in zip(ma, mb))
assert tot == (2, 7, -1)
box(ax, 2, 54, 30, 10, 'sujet', label=rf'$a={t3(a)}$'.replace('−', '-'), size='s')
text(ax, 41, 62, r'$\times\,2$', 'varie', 'm')
arrow(ax, (34, 59), (50, 59), 'varie')
box(ax, 52, 54, 30, 10, 'sujet', label=t3(ma))
box(ax, 2, 34, 30, 10, 'autre', label=rf'$b={t3(b)}$'.replace('−', '-'), size='s')
text(ax, 41, 42, r'$\times\,3$', 'varie', 'm')
arrow(ax, (34, 39), (50, 39), 'varie')
box(ax, 52, 34, 30, 10, 'autre', label=t3(mb))
text(ax, 67, 28.5, '+', 'encre', 'l')
text(ax, 20, 14, r'$2a+3b$', 'encre', 'l')
arrow(ax, (34, 14), (50, 14), 'resultat')
box(ax, 52, 9, 30, 10, 'resultat', label=t3(tot))
save(fig, '58-125')
