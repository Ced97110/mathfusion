import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(80)
u, O = 10.0, (52, 30)
P = lambda p: iso(p[0], p[1], p[2], O, u)
A, B = (1, 2, 1), (0, 1, -1)
S = tuple(A[i] + B[i] for i in range(3))
assert S == (1, 3, 0)
comb = lambda s, t: tuple(s * A[i] + t * B[i] for i in range(3))
for e in [(3, 0, 0), (0, 3, 0), (0, 0, 3)]:
    arrow(ax, P((0, 0, 0)), P(e), 'fixe', lw=0.8)
poly(ax, [P(comb(s, t)) for s, t in [(-.4, -.4), (1.5, -.4), (1.5, 1.5), (-.4, 1.5)]], 'sujet')
line(ax, [P(A), P(S), P(B)], 'resultat', lw=1.0, dash=True)
arrow(ax, P((0, 0, 0)), P(A), 'sujet', lw=1.6)
arrow(ax, P((0, 0, 0)), P(B), 'autre', lw=1.6)
arrow(ax, P((0, 0, 0)), P(S), 'resultat', lw=1.8)
disc(ax, *P((0, 0, 0)), 0.9, 'encre')
text(ax, O[0] + 3, O[1] - 3.5, r'$O$', 'encre', 'm')
pa, pb, ps = P(A), P(B), P(S)
text(ax, pa[0] + 2, pa[1] + 3.5, r'$a=(1,2,1)$', 'sujet', 's', ha='left')
text(ax, pb[0] + 2, pb[1] - 3.5, r'$b=(0,1,-1)$', 'autre', 's', ha='left')
text(ax, ps[0] - 2, ps[1] + 4, r'$a+b=(1,3,0)$', 'resultat', 's', ha='right')
text(ax, 8, 6, r'plan $W$', 'sujet', 'm')
save(fig, '58-127')
