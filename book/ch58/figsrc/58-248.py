import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(66)
ox, oy, u = 12, 16, 12
P = lambda a, b: (ox + a * u, oy + b * u)
arrow(ax, P(-0.3, 0), P(3.4, 0), 'sujet', lw=1.2)
arrow(ax, P(0, -0.3), P(0, 3.4), 'autre', lw=1.2)
arrow(ax, P(-0.3, -0.3), P(3.2, 3.2), 'varie', lw=1.2)
text(ax, P(3.4, 0)[0] - 1, P(3.4, 0)[1] - 4, 'X', 'sujet', 'm', weight='bold')
text(ax, P(0, 3.4)[0] + 4, P(0, 3.4)[1], 'Y', 'autre', 'm', weight='bold')
text(ax, P(3.2, 3.2)[0] + 4, P(3.2, 3.2)[1], 'Z', 'varie', 'm', weight='bold')
# (1, 1) = (1, 0) + (0, 1)
line(ax, [P(1, 0), P(1, 1)], 'resultat', dash=True)
line(ax, [P(0, 1), P(1, 1)], 'resultat', dash=True)
disc(ax, *P(1, 0), 1.2, 'sujet'); disc(ax, *P(0, 1), 1.2, 'autre'); disc(ax, *P(1, 1), 1.5, 'resultat')
text(ax, P(1, 0)[0] + 1, P(1, 0)[1] - 4, '(1, 0)', 'sujet', 's')
text(ax, P(0, 1)[0] - 6.5, P(0, 1)[1] + 3, '(0, 1)', 'autre', 's')
text(ax, P(1, 1)[0] + 4.5, P(1, 1)[1] - 3.5, '(1, 1)', 'resultat', 's', weight='bold')
text(ax, 71, 46, 'deux écritures', 'resultat', 's', weight='bold')
text(ax, 71, 41.5, 'de (1, 1)', 'resultat', 's', weight='bold')
