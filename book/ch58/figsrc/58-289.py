import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(74)
text(ax, 44, 69, r'première coordonnée dans $\mathbb{Z}^2$', 'fixe', 's')
f = numberline(ax, 8, 70, 40, 0, 2, step=1, arrow_right=False)
disc(ax, f(1), 40, 1.5, 'sujet')
disc(ax, f(2), 40, 1.5, 'varie')
text(ax, f(1), 33, '(1, 0)', 'sujet', 's')
text(ax, f(2), 33, '(2, 0)', 'varie', 's')
arrow(ax, (f(1) + 1, 43.5), (f(2) - 1, 43.5), 'resultat', lw=1.2, curve=-0.4)
text(ax, (f(1) + f(2)) / 2, 54, r'$\times 2$ : un entier', 'resultat', 's')
arrow(ax, (f(2) - 1, 36.5), (f(1) + 1, 36.5), 'limite', lw=1.2, curve=-0.4)
text(ax, 66, 26, r'$\times \frac{1}{2}$ : pas un entier', 'limite', 's')
box(ax, 4, 6, 80, 10, 'fixe', label='différence : diviser ou non', size='s')
text(ax, 44, 20.5, r'avec des fractions : $\frac{1}{2}$ existe', 'resultat', 's')
save(fig, '58-289')
