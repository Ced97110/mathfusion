import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(68)
n = lambda v: str(v).replace('-', '−')
f = lambda x1, x2: (x1, 2 * x1 + x2, x1 - x2)
t3 = lambda t: '(' + ', '.join(n(v) for v in t) + ')'
p, q = (1, 2), (2, 3)
s = (p[0] + q[0], p[1] + q[1])
assert f(*s) == (3, 11, -2) and tuple(a + b for a, b in zip(f(*p), f(*q))) == f(*s)
box(ax, 2, 52, 28, 10, 'sujet', label=t3(f(*p)))
text(ax, 16, 48.5, 'paramètres 1 et 2', 'varie', 's')
text(ax, 16, 43.5, '+', 'encre', 'l')
box(ax, 2, 31, 28, 10, 'autre', label=t3(f(*q)))
text(ax, 16, 27.5, 'paramètres 2 et 3', 'varie', 's')
arrow(ax, (32, 41), (54, 41), 'resultat')
box(ax, 56, 36, 30, 10, 'resultat', label=t3(f(*s)))
text(ax, 71, 32.5, 'paramètres 3 et 5', 'resultat', 's')
text(ax, 44, 14, r'$1+2=3$  et  $2+3=5$', 'varie', 'm')
text(ax, 44, 6, 'les paramètres s’additionnent', 'varie', 's')
save(fig, '58-124')
