import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(74)
n = lambda v: str(v).replace('-', '−')
v1, v2 = (1, 2), (0, 1)
comb = lambda s, t: (s * v1[0] + t * v2[0], s * v1[1] + t * v2[1])
s1, s2 = (2, 3), (1, 5)
s3 = (s1[0] + s2[0], s1[1] + s2[1])
assert comb(*s1) == (2, 7) and comb(*s2) == (1, 7) and s3 == (3, 8) and comb(*s3) == (3, 14)
text(ax, 22, 69, 'scalaires devant (1, 2) et (0, 1)', 'fixe', 's')
text(ax, 72, 69, 'vecteur obtenu', 'fixe', 's')
for s, role, y in [(s1, 'sujet', 52), (s2, 'autre', 36)]:
    box(ax, 2, y, 52, 10, role, label=rf'${s[0]}\,(1,2)+{s[1]}\,(0,1)$')
    t = comb(*s)
    box(ax, 62, y, 24, 10, role, label=rf'$({t[0]},{t[1]})$')
text(ax, 28, 46.5, '+', 'encre', 'l')
text(ax, 74, 46.5, '+', 'encre', 'l')
text(ax, 28, 30.5, r'$2+1=3$ ; $3+5=8$', 'varie', 'm')
arrow(ax, (28, 27.5), (28, 22), 'varie')
box(ax, 2, 10, 52, 10, 'resultat', label=rf'${s3[0]}\,(1,2)+{s3[1]}\,(0,1)$')
t = comb(*s3)
box(ax, 62, 10, 24, 10, 'resultat', label=rf'$({t[0]},{t[1]})$', weight='bold')
text(ax, 44, 3.5, 'même forme : encore une combinaison', 'resultat', 's')
save(fig, '58-141')
