import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); from figstyle import *
fig, ax = canvas(78)
# le carré bâti sur (1, 0), (0, 1) devient le parallélogramme bâti sur (2, 1), (1, 3)
ox, oy, u = 10, 7, 15.0
P = lambda x, y: (ox + x * u, oy + y * u)
poly(ax, [P(0, 0), P(1, 0), P(1, 1), P(0, 1)], 'fixe')
poly(ax, [P(0, 0), P(2, 1), P(3, 4), P(1, 3)], 'resultat', fill=True)
poly(ax, [P(0, 0), P(1, 0), P(1, 1), P(0, 1)], 'fixe')
arrow(ax, P(0, 0), P(1, 0), 'sujet', lw=1.6)
arrow(ax, P(0, 0), P(0, 1), 'varie', lw=1.6)
arrow(ax, P(0, 0), P(2, 1), 'sujet', lw=1.6)
arrow(ax, P(0, 0), P(1, 3), 'varie', lw=1.6)
disc(ax, *P(3, 4), 1.1, 'resultat')
text(ax, P(1, 0)[0] + 1, P(1, 0)[1] - 2.8, '(1, 0)', 'sujet', 's', ha='left')
text(ax, P(0, 1)[0] - 1.5, P(0, 1)[1] + 1.5, '(0, 1)', 'varie', 's', ha='right')
text(ax, P(2, 1)[0] + 1.5, P(2, 1)[1] - 2.5, '(2, 1)', 'sujet', 's', ha='left')
text(ax, P(1, 3)[0] - 1.5, P(1, 3)[1] + 1, '(1, 3)', 'varie', 's', ha='right')
text(ax, P(3, 4)[0] + 2, P(3, 4)[1], '(1, 1) ↦ (3, 4)', 'resultat', 's', ha='left')
text(ax, 16, 3, 'le carré', 'fixe', 's')
text(ax, 66, 44, 'le parallélogramme\nest bâti sur\nles deux colonnes', 'resultat', 's')
save(fig, '58-202')
